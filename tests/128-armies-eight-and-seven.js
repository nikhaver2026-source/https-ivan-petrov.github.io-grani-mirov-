 const errors=[];
 page.on('pageerror',e=>errors.push(String(e)));
 page.on('console',m=>{if(m.type()==='error')errors.push('console: '+m.text());});
 await page.goto(process.argv[2]);
 await page.waitForTimeout(800);
 await page.evaluate(()=>{window.__said=[];const s=Speech.say.bind(Speech);
  Speech.say=(t,o)=>{__said.push(String(t));return s(t,o);};
  window.__played=[];const bp=Bank.play.bind(Bank);
  Bank.play=(r,o)=>{__played.push(r);return bp(r,o);};
  try{enterGame();}catch(e){}});
 await page.waitForTimeout(300);

 /* ── 1. восемь свойств ── */
 const свойства=await page.evaluate(()=>{
  const a=Armies.state(0);
  return {
   сколько:ARMY_TRAITS.length,
   имена:ARMY_TRAITS.map(t=>t.n),
   полны:ARMY_TRAITS.every(t=>t.n&&t.о&&SOUND_BANK[t.звук]),
   звуковСвоих:new Set(ARMY_TRAITS.map(t=>t.звук)).size,
   вСостоянии:ARMY_TRAITS.every(t=>typeof a[t.id]==="number"),
   отсутствуют:ARMY_TRAITS.filter(t=>typeof a[t.id]!=="number").map(t=>t.id)};});
