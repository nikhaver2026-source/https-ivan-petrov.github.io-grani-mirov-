/* ═══════════════════════════════════════════════════════════════════════
   НАБОР 141: ДЕСЯТЬ РЕДКОСТЕЙ И СЕМЬ КАЧЕСТВ (§10 мастер-промпта)

   У вещи две мерки, и они о разном: редкость говорит, ЧТО это за вещь,
   качество — насколько ровно её сделали. §10 просит десяти редкостей и
   семи качеств. Было шесть и шесть у вещей, семь и шесть у артефактов.

   ЧТО ПРОВЕРЯЕТСЯ.

   1. Десять редкостей, семь качеств, десять материалов и десять цен —
      и то же самое у артефактов.
   2. Первые шесть ступеней стоят на прежних местах: сохранённые вещи
      читаются без правки.
   3. Каждое качество и каждый материал склоняются во всех трёх родах.
   4. Имя собирается для всех семидесяти пар и ни разу не пустое.
   5. Цена, мощь, уровень и множитель качества растут от ступени к
      ступени; вероятность сбоя падает.
   6. Верхние четыре редкости достаются не сразу: предел поднимается на
      десятом, двадцатом, тридцатом и сороковом уровне.
   7. Шесть прежних редкостей выпадают как прежде на любом уровне.
   8. Верхние редкости вправду редки, а не «изредка».
   9. Артефакт высшего ранга и высшего качества собирается и дороже
      простого на порядки.
  10. Седьмое качество артефакта не подводит вовсе.
  11. Самопроверка мира держит строку «rarity»; глава, README и docs.
   ═══════════════════════════════════════════════════════════════════════ */
const {chromium}=require('playwright');
const fs=require('fs'),path=require('path');
const results=[];
const check=(n,c,e)=>results.push((c?'PASS':'FAIL')+' — '+n+(e!==undefined?' :: '+JSON.stringify(e):''));

(async()=>{
 const browser=await chromium.launch();
 const ctx=await browser.newContext({hasTouch:true,isMobile:true,viewport:{width:390,height:780}});
 const page=await ctx.newPage();
 const errors=[];
 page.on('pageerror',e=>errors.push(String(e)));
 page.on('console',m=>{if(m.type()==='error')errors.push('console: '+m.text());});
 await page.goto(process.argv[2]);
 await page.waitForTimeout(800);
 await page.evaluate(()=>{try{enterGame();}catch(e){}});
 await page.waitForTimeout(300);

 /* ── 1–2. состав и совместимость ── */
 const состав=await page.evaluate(()=>({
  ranks:RANKS.length,qual:QUAL.length,mat:MAT.length,price:RANKPRICE.length,
  artRanks:ART_RANKS.length,artQual:ART_QUAL.length,
  прежниеРанги:RANKS.slice(0,6),
  прежниеКачества:QUAL.slice(0,6),
  прежниеМатериалы:MAT.slice(0,6),
  прежниеЦены:RANKPRICE.slice(0,6),
  новыеРанги:RANKS.slice(6),новыеМатериалы:MAT.slice(6),
  седьмое:QUAL[6],
  артНовые:ART_RANKS.slice(7).map(r=>r.n),артСедьмое:ART_QUAL[6].n}));
 check('десять редкостей, семь качеств, десять материалов и десять цен',
  состав.ranks===10&&состав.qual===7&&состав.mat===10&&состав.price===10,состав);
 check('у артефактов та же лестница: десять рангов и семь качеств',
  состав.artRanks===10&&состав.artQual===7&&состав.артНовые.length===3,состав);
 check('первые шесть ступеней стоят на прежних местах: старые вещи читаются без правки',
  String(состав.прежниеРанги)==="Обычный,Необычный,Редкий,Эпический,Легендарный,Божественный"
  &&String(состав.прежниеКачества)==="Грубое,Простое,Добротное,Отличное,Превосходное,Благословенное"
  &&String(состав.прежниеМатериалы)==="кожаный,железный,стальной,серебряный,мифриловый,драконий"
  &&String(состав.прежниеЦены)==="30,80,220,600,1600,5000",состав);
 check('четыре новых редкости и четыре новых материала названы, седьмое качество тоже',
  состав.новыеРанги.length===4&&состав.новыеМатериалы.length===4
  &&состав.седьмое==="Нерушимое"&&состав.артСедьмое==="нерушимое",состав);

 /* ── 3–4. склонения и имена ── */
 const имена=await page.evaluate(()=>{
  const плохие=[],пустые=[];
  ["м","ж","с"].forEach(р=>{
   if(QUAL_R[р].length!==QUAL.length)плохие.push("качества "+р+": "+QUAL_R[р].length);
   if(MAT_R[р].length!==MAT.length)плохие.push("материалы "+р+": "+MAT_R[р].length);});
  let всего=0;
  const роды={"Меч":"м","Кольчуга":"ж","Кольцо":"с"};
  Object.keys(роды).forEach(тип=>{
   for(let q=0;q<QUAL.length;q++)for(let m=0;m<MAT.length;m++){
    всего++;
    const n=itemName(тип,q,m);
    if(!n||/undefined/.test(n)||n.split(" ").length<3){пустые.push(`${тип} ${q} ${m}: ${n}`);continue;}
    const слова=n.split(" ");
    const р=роды[тип];
    if(слова[0]!==QUAL_R[р][q]||слова[1]!==MAT_R[р][m])плохие.push(`${тип} ${q} ${m}: ${n}`);}});
  return {плохие,пустые,всего,
   примеры:[itemName("Меч",6,9),itemName("Кольчуга",6,8),itemName("Кольцо",6,7)]};});
 check('каждое качество и каждый материал склоняются во всех трёх родах',
  имена.плохие.length===0,имена.плохие.slice(0,4));
 check('имя собирается для всех семидесяти пар в каждом роде и ни разу не пустое',
  имена.всего===3*7*10&&имена.пустые.length===0,имена);
 check('новые ступени читаются по-русски в мужском, женском и среднем роде',
  имена.примеры[0]==="Нерушимый изначальный меч"
  &&имена.примеры[1]==="Нерушимая предтеченская кольчуга"
  &&имена.примеры[2]==="Нерушимое лунное кольцо",имена.примеры);

 /* ── 5. лестницы растут ── */
 const рост=await page.evaluate(()=>({
  цена:RANKPRICE.every((v,i)=>i===0?v>0:v>RANKPRICE[i-1]),
  мощь:ART_RANKS.every((r,i)=>i===0||r.мощь>ART_RANKS[i-1].мощь),
  уровень:ART_RANKS.every((r,i)=>i===0||r.уровень>=ART_RANKS[i-1].уровень),
  артЦена:ART_RANKS.every((r,i)=>i===0||r.цена>ART_RANKS[i-1].цена),
  свойств:ART_RANKS.every((r,i)=>i===0||r.свойств>=ART_RANKS[i-1].свойств),
  качК:ART_QUAL.every((q,i)=>i===0||q.k>ART_QUAL[i-1].k),
  качПорог:ART_QUAL.every((q,i)=>i===0||q.порог>ART_QUAL[i-1].порог),
  сбой:ART_QUAL.every((q,i)=>i===0||q.сбой<=ART_QUAL[i-1].сбой),
  идПоПорядку:ART_RANKS.every((r,i)=>r.id===i)&&ART_QUAL.every((q,i)=>q.id===i),
  цена0:RANKPRICE[0],цена9:RANKPRICE[9]}));
 check('цена вещи растёт от ступени к ступени: от тридцати до двухсот сорока тысяч',
  рост.цена&&рост.цена0===30&&рост.цена9===240000,рост);
 check('у артефактов растут мощь, уровень, цена и число свойств, и все по порядку',
  рост.мощь&&рост.уровень&&рост.артЦена&&рост.свойств&&рост.идПоПорядку,рост);
 check('множитель качества растёт, порог растёт, вероятность сбоя падает',
  рост.качК&&рост.качПорог&&рост.сбой,рост);

 /* ── 6–8. предел по уровню и настоящая редкость ── */
 const выпадение=await page.evaluate(()=>{
  const считать=lvl=>{const m={};
   for(let i=0;i<8000;i++){const it=genLoot(100+i%79,200+Math.floor(i/79),i*7+3,lvl);
    m[it.rank]=(m[it.rank]||0)+1;}
   return m;};
  const с=(m,r)=>Number(m[r])||0;
  const ур1=считать(1),ур10=считать(10),ур20=считать(20),ур40=считать(40);
  return {ур1,ур10,ур20,ур40,
   потолок1:Math.max(...Object.keys(ур1).map(Number)),
   потолок10:Math.max(...Object.keys(ур10).map(Number)),
   потолок20:Math.max(...Object.keys(ур20).map(Number)),
   потолок40:Math.max(...Object.keys(ур40).map(Number)),
   прежние1:[0,1,2,3,4].map(r=>с(ур1,r)),
   прежние40:[0,1,2,3,4].map(r=>с(ур40,r)),
   верхних40:[6,7,8,9].reduce((a,r)=>a+с(ур40,r),0),
   всего:8000};});
 check('на первом уровне выше шестой редкости ничего не выпадает',
  выпадение.потолок1===5,{потолок:выпадение.потолок1,ур1:выпадение.ур1});
 check('предел поднимается с уровнем: на десятом седьмая, на двадцатом восьмая',
  выпадение.потолок10>=6&&выпадение.потолок10<=6&&выпадение.потолок20>=7,выпадение);
 check('шесть прежних редкостей выпадают одинаково на любом уровне',
  String(выпадение.прежние1)===String(выпадение.прежние40),выпадение);
 check('верхние редкости вправду редки: меньше сотой доли всех находок',
  выпадение.верхних40>0&&выпадение.верхних40<выпадение.всего*0.01,
  {верхних:выпадение.верхних40,всего:выпадение.всего});

 /* ── 9–10. артефакт высшей ступени ── */
 const артефакт=await page.evaluate(()=>{
  const высший=ART.make({дом:"war",ранг:9,кач:6,seed:5});
  const простой=ART.make({дом:"war",ранг:0,кач:0,seed:5});
  const ст=ART.stats(высший).статы;
  return {ранг:высший.ранг,кач:высший.кач,имя:высший.имя,
   статов:Object.keys(ст).length,
   ценаВысшего:Math.round(ART.price(высший)),ценаПростого:Math.round(ART.price(простой)),
   сбойВысшего:ART_QUAL[6].сбой,сбойГрубого:ART_QUAL[0].сбой,
   /* Ранг и качество сверх лестницы обрезаются, а не ломают вещь. */
   обрез:(()=>{const a=ART.make({дом:"war",ранг:99,кач:99,seed:3});
    return a.ранг===ART_RANKS.length-1&&a.кач===ART_QUAL.length-1;})()};});
 check('артефакт высшего ранга и качества собирается и несёт больше свойств',
  артефакт.ранг===9&&артефакт.кач===6&&артефакт.имя&&артефакт.статов>=3,артефакт);
 check('он дороже простого на порядки',
  артефакт.ценаВысшего>артефакт.ценаПростого*500,артефакт);
 check('седьмое качество не подводит вовсе, а грубое подводит часто',
  артефакт.сбойВысшего===0&&артефакт.сбойГрубого>0.15,артефакт);
 check('ранг и качество сверх лестницы обрезаются, а не ломают вещь',артефакт.обрез,артефакт);

 /* ── 11. самопроверка и тексты ── */
 const свод=await page.evaluate(()=>{const r=worldSelfCheck();
  const гл=GUIDE.find(g=>/Десять редкостей/i.test(g.title));
  return {r:r.find(x=>x.id==="rarity"),m:r.find(x=>x.id==="merit"),
   плохие:r.filter(x=>!x.ok).map(x=>x.id),
   глава:!!гл,строк:гл?гл.body.length:0};});
 check('самопроверка мира держит зелёную строку «rarity»',
  !!свод.r&&свод.r.ok===true,свод.r);
 check('прежняя строка «merit» тоже зелёная: десять рангов её не сломали',
  !!свод.m&&свод.m.ok===true,свод.m);
 check('вся остальная самопроверка мира тоже зелёная',свод.плохие.length===0,свод.плохие);
 check('в руководстве есть глава о десяти редкостях',свод.глава&&свод.строк>=6,свод);

 const ROOT=path.resolve(__dirname,'..');
 const readme=fs.readFileSync(path.join(ROOT,'README.md'),'utf8');
 const mir=fs.readFileSync(path.join(ROOT,'docs','МИР.md'),'utf8');
 check('README рассказывает о десяти редкостях, семи качествах и пределе по уровню',
  /Десять редкостей и семь качеств/i.test(readme)&&/Нерушимое/.test(readme)
  &&/достаются не сразу/i.test(readme));
 check('docs/МИР.md держит формулу предела и обе лестницы',
  /RANKPRICE/.test(mir)&&/ART_QUAL/.test(mir)&&/предел/.test(mir)&&/QUAL_R/.test(mir));

 check('ошибок на странице нет',errors.length===0,errors.slice(0,3));

 await browser.close();
 console.log(results.join('\n'));
 const bad=results.filter(r=>r.startsWith('FAIL'));
 console.log(`\nИТОГ: ${results.length-bad.length}/${results.length}`);
 process.exit(bad.length?1:0);
})();
