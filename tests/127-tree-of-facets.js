/* ═══════════════════════════════════════════════════════════════════════
   НАБОР 127: ДРЕВО ГРАНЕЙ (§44.2 брифа)

   §44.2 требует не одно дерево, а лес взаимосвязанных ветвей: шесть ветвей
   и сорок шесть умений — боевых, выживательных, исследовательских,
   магических, социальных и ремесленных.

   В мире были крупные ветви силы: они считают жизнь целиком — «боевое
   мастерство», «выживание», «торговля». Мелкого счёта не было: меч и лук
   росли одним числом, поиск воды и разведение огня — другим.

   ЧТО ПРОВЕРЯЕТСЯ.

   1. Шесть ветвей, сорок шесть умений; у каждого имя, ветвь, пять ступеней,
      пять даров, пять чисел, свой счёт, своя запись и связь с другой ветвью.
   2. Все записи настоящие (есть в банке) и у каждого умения своя.
   3. Растёт от дела, а не от уровня: уровень героя ничего не двигает,
      а сделанное дело двигает именно своё умение и не трогает чужое.
   4. Пять ступеней берутся по своим порогам, и ни одна не пропускается.
   5. Лес, а не шесть деревьев: связанное умение на третьей ступени даёт
      ступень сверх заработанной, и связь не кормит сама себя по кругу.
   6. Дар настоящий (§38): атака, защита, сокрушительный удар, нужда, скан,
      цена, доброе имя, риск у горна, цена и сила чары — меняются числом.
   7. Оружие в руке решает, какое боевое умение работает.
   8. Ступень слышна: при подъёме звучит запись умения и голос ветви, и о
      ней говорят словами.
   9. Древо стоит в окне «Герой» и читается голосом.
  10. Самопроверка мира держит строку «tree»; руководство, README и docs
      рассказывают о лесе из шести ветвей.
   ═══════════════════════════════════════════════════════════════════════ */
