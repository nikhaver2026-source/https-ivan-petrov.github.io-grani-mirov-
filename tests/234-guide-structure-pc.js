  const все=GUIDE_PARTS.reduce((a,p)=>a.concat(p[2]),[]);
  const частиОк=все.length===GUIDE.length&&new Set(все).size===GUIDE.length;
  const перваяЧасть=GUIDE_PARTS[0][2].map(n=>GUIDE[n-1].title.replace(/^Глава \d+\. /,""));
