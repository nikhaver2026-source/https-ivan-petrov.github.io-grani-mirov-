 const ctx=await browser.newContext({hasTouch:true,isMobile:true,viewport:{width:390,height:780}});
 const page=await ctx.newPage();
 const errors=[];page.on('pageerror',e=>errors.push(String(e)));
 page.on('console',m=>{
  if(m.type()==='error'&&!/Failed to load resource|fetching the script|ServiceWorker/i.test(m.text()))errors.push('console: '+m.text());});
 await page.goto(process.argv[2]);await page.waitForTimeout(700);
 await page.evaluate(()=>enterGame());await page.waitForTimeout(500);

 /* ── 1. Таблица собрана ── */
 const таблица=await page.evaluate(()=>{
  const беды=[];let всего=0;
  for(const имя in RES_SORTS){
   const список=RES_SORTS[имя];всего+=список.length;
   if(!LAND_RES.includes(имя))беды.push("сорта у неизвестного ресурса: "+имя);
   список.forEach(с=>{
    if(!с.id||!с.n||!с.о)беды.push(имя+"/"+(с.id||"?")+": нет имени или описания");
    if(!(с.вес>0))беды.push(имя+"/"+с.id+": нет веса");
    (с.био||[]).forEach(b=>{if(!BIOME_BY_ID[b])беды.push(имя+"/"+с.id+": нет биома "+b);});});}
  const безЦены=Object.keys(SORT_GOODS).filter(k=>!(RES_BASE[k]>0));
  const безЗнака=Object.keys(SORT_GOODS).filter(k=>!RESICON[k]);
  /* у каждого сорта с товаром товар должен быть описан ценой */
  const сироты=[];
  for(const имя in RES_SORTS)RES_SORTS[имя].forEach(с=>{
   if(с.товар&&!SORT_GOODS[с.товар])сироты.push(имя+"/"+с.id+"→"+с.товар);});
  return {ресурсов:Object.keys(RES_SORTS).length,всего,беды,безЦены,безЗнака,сироты};});
 check('сорта есть у каждого собираемого ресурса',таблица.ресурсов>=9,таблица.ресурсов);
 check('сортов не меньше сорока',таблица.всего>=40,таблица.всего);
 check('в таблице сортов нет изъянов',!таблица.беды.length,таблица.беды.slice(0,6));
 check('у каждого редкого товара есть цена и значок',
  !таблица.безЦены.length&&!таблица.безЗнака.length,
  {безЦены:таблица.безЦены,безЗнака:таблица.безЗнака});
 check('ни один сорт не ссылается на несуществующий товар',!таблица.сироты.length,таблица.сироты);

 /* ── 2. Каждый сорт достижим ──
    Спрашиваем сорт напрямую у клеток, чей биом подходит, и отдельно проходим
    ночью и зимой: часть сортов бывает только в темноте или в стужу. */
 const достижимость=await page.evaluate(()=>{
  const виден={};
  const проход=(день,час)=>{
   G.day=день;G.hour=час;
   for(let i=0;i<9000;i++){
    const x=(i*7919)%WORLD,y=(i*104729)%WORLD;
    for(const имя in RES_SORTS){
     const с=safeFn(()=>resSortAt(x,y,имя),null);
     if(с)виден[имя+"/"+с.id]=(виден[имя+"/"+с.id]||0)+1;}}};
  проход(30,13);   /* лето, день */
  проход(30,1);    /* лето, ночь */
  проход(80,13);   /* зима, день */
  проход(80,1);    /* зима, ночь */
  const нет=[];
  for(const имя in RES_SORTS)RES_SORTS[имя].forEach(с=>{
   if(!виден[имя+"/"+с.id])нет.push(имя+"/"+с.id);});
  const редчайшие=Object.entries(виден).sort((a,b)=>a[1]-b[1]).slice(0,4).map(([k,v])=>k+":"+v);
  return {встретилось:Object.keys(виден).length,нет,редчайшие};});
 check('каждый сорт достижим хотя бы в одну пору и час',
  !достижимость.нет.length,достижимость.нет.slice(0,10));

 /* ── 3. Ночные и сезонные сорта не встречаются вне своей поры ── */
 const условные=await page.evaluate(()=>{
  const днём={},ночью={},летом={},зимой={};
  const собрать=(куда,день,час)=>{
   G.day=день;G.hour=час;
   for(let i=0;i<9000;i++){
    const x=(i*7919)%WORLD,y=(i*104729)%WORLD;
    for(const имя in RES_SORTS){
     const с=safeFn(()=>resSortAt(x,y,имя),null);
     if(с)куда[с.id]=(куда[с.id]||0)+1;}}};
  собрать(днём,30,13);собрать(ночью,30,1);
  собрать(летом,30,13);собрать(зимой,80,13);
  return {светлякиДень:днём["светящиеся"]||0,светлякиНочь:ночью["светящиеся"]||0,
   звёздоцветДень:днём["звёздоцвет"]||0,звёздоцветНочь:ночью["звёздоцвет"]||0,
   сладкиеЛето:летом["сладкие"]||0,сладкиеЗима:зимой["сладкие"]||0,
   морозныеЛето:летом["морозные"]||0,морозныеЗима:зимой["морозные"]||0};});
 check('светляки и звёздоцвет бывают только ночью',
  условные.светлякиДень===0&&условные.звёздоцветДень===0&&
  условные.светлякиНочь>0&&условные.звёздоцветНочь>0,условные);
 check('медовая ягода — летняя, морозная — зимняя',
  условные.сладкиеЗима===0&&условные.морозныеЛето===0&&
  условные.сладкиеЛето>0&&условные.морозныеЗима>0,условные);

