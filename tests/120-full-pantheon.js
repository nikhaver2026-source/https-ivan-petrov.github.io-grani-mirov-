/* ═══════════════════════════════════════════════════════════════════════
   НАБОР 120: ВЕСЬ ПАНТЕОН ЖИВОЙ (§24 брифа)

   Малые боги были сделаны как надо: культ, святое место, обряд, жрецы,
   табу, артефакт, чудо, праздник, погода, цена, школа и голос. Великие
   знали только миф, дар и запрет; тёмные — только обряд и плату. Их
   нельзя было ни спросить о культе, ни встретить их праздник, ни нарушить
   их табу: половина пантеона была справкой, а не силой мира.

   ЧТО ПРОВЕРЯЕТСЯ.

   1. Семьдесят один бог: двенадцать великих, тридцать два малых и
      двадцать семь тёмных; света и равновесия не меньше тридцати двух,
      тёмных не меньше тридцати пяти.
   2. У КАЖДОГО полное досье, и всё в нём настоящее: звук есть в банке,
      школа — среди чар, товар — среди ресурсов мира, друг и враг — боги.
   3. Круг праздников в семьдесят два дня, и день у каждого свой.
   4. Праздник виден миру: погода тянется к своей, товар дешевеет, чары
      школы дешевеют на единицу маны, у мирного бога осады стоят.
   5. Табу работает на все шесть ключей, а не только на убийство, и берёт
      только у того, кто богом дорожит.
   6. Молитва идёт любому богу: великому — в общую книгу веры, малому и
      тёмному — в свою; на десятой благосклонности приходит чудо с
      артефактом.
   7. Житель в праздник бога своего народа уступчивее, в праздник
      соперника — упрямее.
   8. Окно пантеона показывает всех, самопроверка мира держит строку
      «pantheon», руководство и README о том рассказывают.
   ═══════════════════════════════════════════════════════════════════════ */
const {chromium}=require('playwright');
const fs=require('fs'),path=require('path');
const results=[];
const check=(n,c,e)=>results.push((c?'PASS':'FAIL')+' — '+n+(e!==undefined?' :: '+JSON.stringify(e):''));

(async()=>{
 const browser=await chromium.launch();
 const ctx=await browser.newContext({hasTouch:true,isMobile:true,viewport:{width:390,height:780}});
 const page=await ctx.newPage();
 const errors=[];
 page.on('pageerror',e=>errors.push(String(e)));
 page.on('console',m=>{if(m.type()==='error')errors.push('console: '+m.text());});
 await page.goto(process.argv[2]);
 await page.waitForTimeout(800);

 /* ── 1–3. состав, досье, круг ── */
 const состав=await page.evaluate(()=>{
  const все=GODS_ALL,дни=все.map(g=>g.праздник);
  const плохо=f=>все.filter(g=>!g[f]).map(g=>g.id);
  return {
   всего:все.length,
   великих:Gods.ofRank("великий").length,малых:Gods.ofRank("малый").length,тёмных:Gods.ofRank("тёмный").length,
   счёт:Gods.counts(),круг:Gods.cycle,
   пусто:{культ:плохо("культ"),святое:плохо("святое"),жрецы:плохо("жрецы"),обряд:плохо("обряд"),
    табу:плохо("табу"),артефакт:плохо("артефакт"),чудо:плохо("чудо"),сфера:плохо("сфера")},
   звукНеИзБанка:все.filter(g=>!SOUND_BANK[g.звук]).map(g=>g.id),
   школаНеСуществует:все.filter(g=>!SCHOOLS.some(s=>s.id===g.школа)).map(g=>g.id),
   товарНеСуществует:все.filter(g=>!RES_BASE[g.цена&&g.цена.res]).map(g=>g.id),
   родняНеБоги:все.filter(g=>!GOD_ANY_BY_ID[g.друг]||!GOD_ANY_BY_ID[g.враг]).map(g=>g.id),
   ключНеЗнаком:все.filter(g=>!Gods.ТАБУ[g.ключ]).map(g=>g.id),
   дарНеЗнаком:все.filter(g=>["hp","mana","water","gold","xp","atk","def"].indexOf(g.дарМолитвы||g.дар)<0).map(g=>g.id),
   дубльДня:дни.filter((v,i,a)=>a.indexOf(v)!==i),
   заКругом:все.filter(g=>!(g.праздник>=1&&g.праздник<=Gods.cycle)).map(g=>g.id),
   звуковУникальных:new Set(все.map(g=>g.звук)).size,
   безСвоего:все.filter(g=>!Gods.byId(g.id)).map(g=>g.id)};});
 check('семьдесят один бог: двенадцать великих, тридцать два малых, двадцать семь тёмных',
  состав.всего===71&&состав.великих===12&&состав.малых===32&&состав.тёмных===27,состав);
 check('света и равновесия не меньше тридцати двух, тёмных не меньше тридцати пяти',
  состав.счёт.свет>=32&&состав.счёт.тьма>=35,состав.счёт);
 check('у каждого бога культ, святое место, жрецы, обряд, табу, артефакт, чудо и сфера',
  Object.values(состав.пусто).every(a=>a.length===0),состав.пусто);
 check('голос каждого бога есть в банке записей и ни один не повторяется',
  состав.звукНеИзБанка.length===0&&состав.звуковУникальных===71,
  {нет:состав.звукНеИзБанка,уник:состав.звуковУникальных});
 check('школа, товар, друг, враг, ключ табу и дар молитвы — настоящие',
  состав.школаНеСуществует.length===0&&состав.товарНеСуществует.length===0
  &&состав.родняНеБоги.length===0&&состав.ключНеЗнаком.length===0&&состав.дарНеЗнаком.length===0,состав);
 check('круг в семьдесят два дня, и день у каждого свой',
  состав.круг===72&&состав.дубльДня.length===0&&состав.заКругом.length===0,
  {круг:состав.круг,дубли:состав.дубльДня});
 check('любого бога находят по имени, какого бы он ни был ранга',состав.безСвоего.length===0,состав.безСвоего);

 await page.evaluate(()=>{try{enterGame();}catch(e){}});
 await page.waitForTimeout(300);

 /* ── 4. праздник виден миру ── */
 const праздник=await page.evaluate(()=>{
  const вел=Gods.ofRank("великий")[0],тём=Gods.ofRank("тёмный")[0];
  const из=(g)=>{
   G.day=g.праздник;
   const w={};w[g.погода]=10;w["Ясно"]=10;w["Снег"]=10;
   const было=w[g.погода];Gods.weather(w);
   return {бог:g.n,погодаБыло:было,погодаСтало:w[g.погода],
    цена:Gods.priceK(g.цена.res),цена_чужая:Gods.priceK("несуществующий товар"),
    мана:Gods.manaDiscount({школа:g.школа}),
    манаЧужая:Gods.manaDiscount({школа:g.школа==="light"?"dark":"light"}),
    праздникСегодня:Gods.festivalToday().map(x=>x.id)};};
  const мирный=GODS_ALL.find(g=>g.мир);
  G.day=мирный.праздник;
  const перемирие=Gods.truceToday();
  G.day=GODS_ALL.find(g=>!g.мир&&g.праздник!==мирный.праздник).праздник;
  const безПеремирия=Gods.truceToday();
  return {великий:из(вел),тёмный:из(тём),перемирие,безПеремирия,мирный:мирный.n};});
 check('в праздник великого небо тянется к его погоде',
  праздник.великий.погодаСтало>праздник.великий.погодаБыло,праздник.великий);
 check('в праздник тёмного его товар дешевеет, а чужой нет',
  праздник.тёмный.цена<1&&праздник.тёмный.цена_чужая===1,праздник.тёмный);
 check('в праздник чары его школы дешевле на единицу маны',
  праздник.великий.мана===1&&праздник.великий.манаЧужая===0,праздник.великий);
 check('в праздник мирного бога осады стоят, в остальные — нет',
  праздник.перемирие===true&&праздник.безПеремирия===false,праздник);

 /* ── 5. табу на все шесть ключей ── */
 const табу=await page.evaluate(()=>{
  const итог={};
  Object.keys(Gods.ТАБУ).forEach(ключ=>{
   const g=GODS_ALL.find(x=>x.ключ===ключ);
   if(!g){итог[ключ]={нет:true};return;}
   G.day=g.праздник;G.faith={};G.faithSmall={};
   Gods.addFavor(g.id,5);
   const до=Gods.favor(g.id);
   Gods.taboo(ключ);
   const после=Gods.favor(g.id);
   /* Чужой ключ в тот же день не трогает. */
   const чужой=ключ==="kill"?"trade":"kill";
   Gods.taboo(чужой);
   итог[ключ]={бог:g.n,ранг:g.ранг,до,после,послеЧужого:Gods.favor(g.id)};});
  /* Тому, кто богом не дорожит, терять нечего. */
  const g=GODS_ALL.find(x=>x.ключ==="kill");
  G.day=g.праздник;G.faith={};G.faithSmall={};
  const незнакомый=Gods.taboo("kill");
  return {итог,незнакомый};});
 const всеКлючи=Object.keys(табу.итог);
 check('табу работает на все шесть ключей, а не только на убийство',
  всеКлючи.length===6&&всеКлючи.every(k=>табу.итог[k].после===табу.итог[k].до-1),табу.итог);
 check('чужой поступок в тот же день благосклонности не стоит',
  всеКлючи.every(k=>табу.итог[k].послеЧужого===табу.итог[k].после),табу.итог);
 check('у того, кто богом не дорожит, табу ничего не отнимает',табу.незнакомый===false);

 /* ── 6. молитва любому богу ── */
 const молитва=await page.evaluate(()=>{
  const вел=Gods.ofRank("великий")[1],тём=Gods.ofRank("тёмный")[1],мал=Gods.ofRank("малый")[0];
  G.faith={};G.faithSmall={};G.godGifts={};G.items=[];
  const из=g=>{const было=Gods.favor(g.id);Gods.addFavor(g.id,4);
   return {бог:g.n,ранг:g.ранг,было,стало:Gods.favor(g.id)};};
  const a=из(вел),b=из(тём),c=из(мал);
  const книга={великийВОбщей:Number(G.faith[вел.id])===4,тёмныйВСвоей:Number(G.faithSmall[тём.id])===4};
  /* Чудо: с десятой благосклонности — артефакт в суму, один раз. */
  Gods.addFavor(вел.id,6);
  const дар1=G.items.indexOf(вел.артефакт)>=0;
  const сколько=G.items.filter(x=>x===вел.артефакт).length;
  Gods.addFavor(вел.id,6);
  return {a,b,c,книга,дар1,сколько,всего:G.items.filter(x=>x===вел.артефакт).length,
   артефакт:вел.артефакт};});
 check('благосклонность растёт у бога любого ранга',
  молитва.a.стало===4&&молитва.b.стало===4&&молитва.c.стало===4,молитва);
 check('великий пишется в общую книгу веры, тёмный — в свою',
  молитва.книга.великийВОбщей&&молитва.книга.тёмныйВСвоей,молитва.книга);
 check('на десятой благосклонности приходит чудо с артефактом, и только один раз',
  молитва.дар1&&молитва.сколько===1&&молитва.всего===1,молитва);

 /* ── 7. житель в праздник своего бога ── */
 const житель=await page.evaluate(()=>{
  const n=getNPC(150,150,0);
  const g=godOfRace(n.race),вр=GOD_ANY_BY_ID[g.враг];
  G.day=1;
  while(Gods.festivalToday().some(x=>x.id===g.id||x.id===(вр&&вр.id)))G.day++;
  const обычно=dlgResist(n,"закрытость");
  G.day=g.праздник;
  const вПраздник=dlgResist(n,"закрытость");
  const сдвиг=Gods.npcShift(n);
  let уСоперника=null;
  if(вр){G.day=вр.праздник;уСоперника=Gods.npcShift(n);}
  return {народ:n.race,бог:g.n,соперник:вр?вр.n:null,обычно,вПраздник,сдвиг,уСоперника};});
 check('в праздник бога своего народа житель уступчивее',
  житель.сдвиг===-8&&житель.вПраздник<житель.обычно,житель);
 check('в праздник бога-соперника — упрямее',житель.уСоперника===6,житель);

 /* ── 8. окно, самопроверка, свод правил ── */
 const свод=await page.evaluate(()=>{
  const c=worldSelfCheck();
  const строки=(c.rows||c);
  const p=(строки.find?строки.find(r=>r&&r.id==="pantheon"):null)||null;
  Gods.renderPantheon();
  const el=document.getElementById("godSmall");
  const строк=el?el.querySelectorAll(".list-line").length:0;
  const гл=GUIDE.find(g=>/Весь пантеон|Боги и праздник/i.test(g.title));
  return {pantheon:p,плохие:(строки.filter?строки.filter(r=>r&&r.ok===false).map(r=>r.id):[]),
   строкОкна:строк,глава:!!гл,строкГлавы:гл?гл.body.length:0};});
 check('самопроверка мира держит зелёную строку «pantheon»',
  !!свод.pantheon&&свод.pantheon.ok===true,свод.pantheon);
 check('вся остальная самопроверка мира тоже зелёная',свод.плохие.length===0,свод.плохие);
 check('окно пантеона показывает всех богов, а не одних малых',
  свод.строкОкна>=72,свод.строкОкна);
 check('в руководстве есть глава о богах и праздниках',
  свод.глава&&свод.строкГлавы>=6,свод);

 /* ── README ── */
 const ROOT=path.resolve(__dirname,'..');
 const readme=fs.readFileSync(path.join(ROOT,'README.md'),'utf8');
 check('README рассказывает о семидесяти одном боге и круге праздников',
  /семидесяти одном боге|семьдесят один бог/i.test(readme)&&/семьдесят(и)? двух дн|круг(е)? праздников/i.test(readme));

 check('ошибок на странице нет',errors.length===0,errors.slice(0,3));

 await browser.close();
 console.log(results.join('\n'));
 const bad=results.filter(r=>r.startsWith('FAIL'));
 console.log(`\nИТОГ: ${results.length-bad.length}/${results.length}`);
 process.exit(bad.length?1:0);
})();
