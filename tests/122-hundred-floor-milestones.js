/* ═══════════════════════════════════════════════════════════════════════
   НАБОР 122: ВЕХИ СТА ЯРУСОВ (§14 брифа)

   §14 требует не просто сотни ярусов, а вех на пути вниз: каждый десятый
   ярус — сюжетный узел, двадцать пятый — усиленный страж, пятидесятый —
   крупное событие, сотый — уникальный комплекс.

   Было иначе. Ярусы отличались кругом глубины, голосом и весом добычи, но
   шли ровно: сотый отличался от девяносто девятого только числом. Спуск на
   сотню ярусов был длинным и одинаковым, и запомнить в нём было нечего.

   ЧТО ПРОВЕРЯЕТСЯ.

   1. Девять узлов на десятых ярусах, три рода крупных событий и двенадцать
      уникальных комплексов; у каждого своё имя, своё слово, своя живая
      запись, и ни одна запись не повторяется.
   2. Узел срабатывает один раз на подземелье и ярус, называет себя, звучит
      своим голосом, даёт свою награду и ложится в летопись.
   3. На пятидесятом ярусе случаются и узел, и крупное событие; событие
      кладёт в суму свою именную находку — и только один раз.
   4. Сотый ярус — уникальный комплекс со своим именем и единственной
      наградой; какой именно, решают координаты, поэтому в одной шахте он
      всегда один и тот же, а в соседней другой.
   5. Страж каждого двадцать пятого яруса усилен, страж сотого — страж дна;
      усиленный и вправду крепче и опаснее соседнего яруса.
   6. Обычный ярус вех не поднимает: девяносто девятый молчит.
   7. Вехи ложатся в сохранение, самопроверка мира держит строку «floors»,
      руководство и README о вехах рассказывают.
   ═══════════════════════════════════════════════════════════════════════ */
const {chromium}=require('playwright');
const fs=require('fs'),path=require('path');
const results=[];
const check=(n,c,e)=>results.push((c?'PASS':'FAIL')+' — '+n+(e!==undefined?' :: '+JSON.stringify(e):''));

(async()=>{
 const browser=await chromium.launch();
 const ctx=await browser.newContext({hasTouch:true,isMobile:true,viewport:{width:390,height:780}});
 const page=await ctx.newPage();
 const errors=[];
 page.on('pageerror',e=>errors.push(String(e)));
 page.on('console',m=>{if(m.type()==='error')errors.push('console: '+m.text());});
 await page.goto(process.argv[2]);
 await page.waitForTimeout(800);
 await page.evaluate(()=>{window.__said=[];const s=Speech.say.bind(Speech);
  Speech.say=(t,o)=>{__said.push(String(t));return s(t,o);};
  try{enterGame();}catch(e){}});
 await page.waitForTimeout(300);

 /* ── 1. состав ── */
 const состав=await page.evaluate(()=>{
  const звуки=DEEP_NODES.map(n=>n.звук)
   .concat(DEEP_EVENTS.map(x=>x.звук),DEEP_COMPLEX.map(x=>x.звук));
  return {
   узлов:DEEP_NODES.length,событий:DEEP_EVENTS.length,комплексов:DEEP_COMPLEX.length,
   ярусыУзлов:DEEP_NODES.map(n=>n.д),
   безИмени:[].concat(DEEP_NODES,DEEP_EVENTS,DEEP_COMPLEX).filter(x=>!x.n||!x.о).length,
   безВещи:DEEP_EVENTS.concat(DEEP_COMPLEX).filter(x=>!x.вещь).length,
   вещейРазных:new Set(DEEP_EVENTS.concat(DEEP_COMPLEX).map(x=>x.вещь)).size,
   звуков:звуки.length,звуковРазных:new Set(звуки).size,
   нетВБанке:звуки.filter(r=>!SOUND_BANK[r])};});
 check('девять узлов на десятых ярусах, три события и двенадцать комплексов',
  состав.узлов===9&&состав.событий===3&&состав.комплексов===12
  &&состав.ярусыУзлов.join(",")==="10,20,30,40,50,60,70,80,90",состав);
 check('у каждой вехи есть имя и слово, у каждой находки своё название',
  состав.безИмени===0&&состав.безВещи===0&&состав.вещейРазных===15,состав);
 check('у каждой вехи своя живая запись, и ни одна не повторяется',
  состав.звуков===24&&состав.звуковРазных===24&&состав.нетВБанке.length===0,состав);

 /* ── 2–4, 6. вехи вживую ── */
 const вехи=await page.evaluate(()=>{
  const речь=()=>__said.join(" | ");
  /* Ставим игрока в подземелье: вехи считаются по шахте и ярусу. */
  G.place={bx:500,by:500,depth:0,stype:"cave_entrance",kind:"dungeon",x:1,y:1};
  G.deepMarks={};G.items=[];G.xp=0;
  const огонь=(d)=>{__said.length=0;const было=deepMilestones(500,500,d);
   return {d,было,слово:речь()};};
  const у10=огонь(10),у25=огонь(25),у50=огонь(50),у99=огонь(99),у100=огонь(100);
  const повтор10=огонь(10),повтор50=огонь(50),повтор100=огонь(100);
  const вещи=G.items.slice();
  /* Соседняя шахта — свой комплекс и свои вехи. */
  const тут=deepComplexAt(500,500),рядом=deepComplexAt(900,300);
  const снова=deepComplexAt(500,500);
  const другая=(()=>{__said.length=0;const было=deepMilestones(900,300,100);
   return {было,слово:речь()};})();
  return {у10,у25,у50,у99,у100,повтор10,повтор50,повтор100,вещи,
   тут:тут.n,рядом:рядом.n,устойчив:снова.n===тут.n,другая,
   вМарках:Object.keys(G.deepMarks||{}).length};});
 check('узел десятого яруса называет себя, даёт награду и ложится в летопись',
  вехи.у10.было.join()==="узел"&&/Узел яруса 10/.test(вехи.у10.слово)
  &&/Забытая застава/.test(вехи.у10.слово),вехи.у10);
 check('двадцать пятый ярус узла не поднимает: там другая веха',
  вехи.у25.было.length===0,вехи.у25);
 check('на пятидесятом случаются и узел, и крупное событие',
  вехи.у50.было.indexOf("узел")>=0&&вехи.у50.было.indexOf("событие")>=0
  &&/Крупное событие на 50-м ярусе/.test(вехи.у50.слово),вехи.у50);
 check('обычный ярус вех не поднимает',вехи.у99.было.length===0,вехи.у99);
 check('сотый ярус — уникальный комплекс со своим именем и наградой',
  вехи.у100.было.join()==="комплекс"&&/это /.test(вехи.у100.слово)
  &&/уносят одно/.test(вехи.у100.слово),вехи.у100);
 check('каждая веха срабатывает один раз',
  вехи.повтор10.было.length===0&&вехи.повтор50.было.length===0
  &&вехи.повтор100.было.length===0,
  {десять:вехи.повтор10.было,пятьдесят:вехи.повтор50.было,сто:вехи.повтор100.было});
 check('находки события и комплекса легли в суму, и каждая по одной',
  вехи.вещи.length===2&&new Set(вехи.вещи).size===2,вехи.вещи);
 check('комплекс выводится из координат: в одной шахте всегда тот же, в соседней другой',
  вехи.устойчив&&вехи.тут!==вехи.рядом&&вехи.другая.было.join()==="комплекс",
  {тут:вехи.тут,рядом:вехи.рядом,другая:вехи.другая.было});

 /* ── 5. стражи ── */
 const стражи=await page.evaluate(()=>{
  const g=(d)=>{const x=guardianAt(500,500,d);return x?{ранг:x.ранг,усилен:!!x.усилен,hp:x.hp,dmg:x.dmg,n:x.n}:null;};
  return {д24:g(24),д25:g(25),д50:g(50),д99:g(99),д100:g(100),
   ранги:{10:deepGuardRank(10).приставка,25:deepGuardRank(25).приставка,100:deepGuardRank(100).приставка},
   множители:{24:deepGuardRank(24).k,25:deepGuardRank(25).k,50:deepGuardRank(50).k,100:deepGuardRank(100).k}};});
 check('страж каждого двадцать пятого яруса усилен, сотого — страж дна',
  стражи.д25.усилен&&стражи.д25.ранг==="усиленный страж"
  &&стражи.д50.усилен&&стражи.д100.ранг==="страж дна"
  &&!стражи.д24.усилен&&!стражи.д99.усилен,стражи.ранги);
 /* Само усиление — правило: множитель ровно 1,7 на каждом двадцать пятом и
    2,4 на сотом. Соседние ярусы сравниваются лишь на «не меньше»: у них
    разные твари из разных пулов, и требовать от выборки точной доли значило
    бы проверять везение с жеребьёвкой, а не усиление. */
 check('усиленный страж и вправду крепче и опаснее соседнего яруса',
  стражи.множители[25]===1.7&&стражи.множители[100]===2.4&&стражи.множители[24]===1
  &&стражи.д25.hp>стражи.д24.hp&&стражи.д100.hp>стражи.д99.hp*1.8,
  {множители:стражи.множители,д24:стражи.д24.hp,д25:стражи.д25.hp,
   д99:стражи.д99.hp,д100:стражи.д100.hp});
 check('усиление названо в имени стража, и его слышно при встрече',
  / — усиленный страж$/.test(стражи.д25.n)&&/ — страж дна$/.test(стражи.д100.n),
  {д25:стражи.д25.n,д100:стражи.д100.n});

 /* ── 7. сохранение, самопроверка, свод правил ── */
 const итог=await page.evaluate(()=>{
  const было=Object.keys(G.deepMarks||{}).length;
  const raw=safeFn(()=>serializeSave(),"")||"";
  const c=worldSelfCheck();const r=(c.rows||c);
  const гл=GUIDE.find(g=>/Вехи ста ярусов/i.test(g.title));
  return {вМарках:было,вСохранении:raw.indexOf("deepMarks")>=0,
   floors:(r.find?r.find(x=>x&&x.id==="floors"):null)||null,
   плохие:(r.filter?r.filter(x=>x&&x.ok===false).map(x=>x.id):[]),
   глава:!!гл,строк:гл?гл.body.length:0};});
 check('вехи ложатся в сохранение',итог.вМарках>0&&итог.вСохранении,итог);
 check('самопроверка мира держит зелёную строку «floors»',
  !!итог.floors&&итог.floors.ok===true,итог.floors);
 check('вся остальная самопроверка мира тоже зелёная',итог.плохие.length===0,итог.плохие);
 check('в руководстве есть глава о вехах ста ярусов',итог.глава&&итог.строк>=5,итог);

 const ROOT=path.resolve(__dirname,'..');
 const readme=fs.readFileSync(path.join(ROOT,'README.md'),'utf8');
 check('README рассказывает о сюжетных узлах, усиленных стражах и уникальном дне',
  /* \w в JavaScript кириллицу не берёт, поэтому окончание пишется явно. */
  /узл/i.test(readme)&&/усиленн/i.test(readme)&&/уникальн[а-яё]* комплекс/i.test(readme));

 check('ошибок на странице нет',errors.length===0,errors.slice(0,3));

 await browser.close();
 console.log(results.join('\n'));
 const bad=results.filter(r=>r.startsWith('FAIL'));
 console.log(`\nИТОГ: ${results.length-bad.length}/${results.length}`);
 process.exit(bad.length?1:0);
})();
