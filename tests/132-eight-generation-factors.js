/* ═══════════════════════════════════════════════════════════════════════
   НАБОР 132: ВОСЕМЬ МНОЖИТЕЛЕЙ ПОРОЖДЕНИЯ (§28 брифа)

   §28 начинается запретом: «Не использовать полностью случайную генерацию».
   И даёт формулу: шаблон + регион + история + культура + экономика +
   опасность + биом + магия.

   Город строился по миру и раньше. Ярус подземелья — нет: комнат четыре
   плюс хеш координат, тварей два плюс хеш, сундуков один плюс хеш. Паспорт
   подземелья описывал и область, и возраст, и род, и магию — а порождение
   всего этого не читало.

   ЧТО ПРОВЕРЯЕТСЯ.

   1. Восемь множителей, у каждого имя, слово и своя живая запись.
   2. Ни один не мёртв: на сорока входах по всей карте каждый хоть раз
      оказывается не нулём. Множитель, который всегда ноль, — формула на
      бумаге.
   3. Разные места дают разные наборы: порождение не одно и то же везде.
   4. Множители читаются из мира, а не выдумываются: подменяешь область,
      возраст, биом или место силы — число меняется.
   5. Ничего не отнимается: при любых восьми числах на ярусе есть тварь,
      спуск, сундук, жила и свет. Прибавки ограничены сверху.
   6. Род подземелья у порождения и у паспорта один и тот же.
   7. Мир устойчив: одно и то же место порождается одинаково дважды.
   8. «Из чего сложено» называет все восемь вслух.
   9. Самопроверка мира держит строку «gen»; руководство, README и docs
      рассказывают о восьми множителях.
   ═══════════════════════════════════════════════════════════════════════ */
