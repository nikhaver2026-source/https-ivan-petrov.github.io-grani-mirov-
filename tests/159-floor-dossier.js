/* ═══════════════════════════════════════════════════════════════════════
   НАБОР 159: ДОСЬЕ ЯРУСА — ТРИНАДЦАТЬ СВОЙСТВ (§19 мастер-промпта)

   §19 требует у каждого из ста уровней подземелья: уникальную геометрию,
   акустику, ресурсы, монстров, NPC, ловушки, тайники, двери, ключи,
   мини-босса, хранителя перехода и уникальный лут. Девять из тринадцати в
   игре уже работали; четырёх не было.

   ЧТО ПРОВЕРЯЕТСЯ.

   1. Жителей яруса двенадцать родов, у каждого слово, голос настоящей
      записью и свой предел глубины.
   2. Мини-боссов четырнадцать, именных находок четырнадцать, и все разные.
   3. У досье все тринадцать свойств, и ни одно не пустое.
   4. Досье выводится, а не хранится: тот же ярус даёт то же самое.
   5. Соседний ярус даёт другое.
   6. Досье не оставляет игрока стоящим на чужом ярусе.
   7. Тайники и двери считаются по самому ярусу, а не назначаются.
   8. Жители есть не на всяком ярусе, и глубже их реже.
   9. Род жителя не уходит глубже своего предела.
  10. Мини-босс есть не на всяком ярусе и появляется не сразу.
  11. Мини-босс и страж перехода — разные вещи, и оба названы.
  12. Строка досье называет все тринадцать свойств.
  13. Веха ставится там, где ей положено, и не ставится где попало.
  14. Команда и кнопка есть, а наверху досье не читается.
  15. Самопроверка держит строку floors13; модуль, глава, README, docs.
   ═══════════════════════════════════════════════════════════════════════ */
const {chromium}=require('playwright');
const fs=require('fs'),path=require('path');
const results=[];
const check=(n,c,e)=>results.push((c?'PASS':'FAIL')+' — '+n+(e!==undefined?' :: '+JSON.stringify(e):''));

(async()=>{
 const browser=await chromium.launch();
 const ctx=await browser.newContext({hasTouch:true,isMobile:true,viewport:{width:390,height:780}});
 const page=await ctx.newPage();
 const errors=[];
 page.on('pageerror',e=>errors.push(String(e)));
 page.on('console',m=>{if(m.type()==='error')errors.push('console: '+m.text());});
 await page.goto(process.argv[2]);
 await page.waitForTimeout(800);
 await page.evaluate(()=>{try{enterGame();}catch(e){}});
 await page.waitForTimeout(300);
 await page.evaluate(()=>{
  window.SAID=[];const o=Speech.say.bind(Speech);
  Speech.say=(t,x)=>{SAID.push(String(t));return o(t,x);};});

 /* ── 1–2. Состав ── */
 const состав=await page.evaluate(()=>{
  const синт=/^(inst|orch|mood|relic|score|folk|depth)\//;
  return {жителей:FLOOR_FOLK.length,уникЖ:new Set(FLOOR_FOLK.map(f=>f.id)).size,
   плохиеЖ:FLOOR_FOLK.filter(f=>!(f.n&&f.о&&f.о.length>20&&f.до>=40&&f.до<=100)).map(f=>f.id),
   синтезЖ:FLOOR_FOLK.filter(f=>!SOUND_BANK[f.звук]||синт.test(SOUND_BANK[f.звук].f[0])).map(f=>f.id),
   боссов:FLOOR_BOSSES.length,уникБ:new Set(FLOOR_BOSSES.map(b=>b.id)).size,
   плохиеБ:FLOOR_BOSSES.filter(b=>!(b.n&&b.о&&b.о.length>20)).map(b=>b.id),
   синтезБ:FLOOR_BOSSES.filter(b=>!SOUND_BANK[b.звук]||синт.test(SOUND_BANK[b.звук].f[0])).map(b=>b.id),
   находок:FLOOR_PRIZES.length,уникН:new Set(FLOOR_PRIZES).size};});
 check('жителей яруса двенадцать родов, у каждого слово, голос настоящей записью и свой предел глубины',
  состав.жителей===12&&состав.уникЖ===12&&состав.плохиеЖ.length===0&&состав.синтезЖ.length===0,состав);
 check('мини-боссов четырнадцать и именных находок четырнадцать, все разные и со своим голосом',
  состав.боссов===14&&состав.уникБ===14&&состав.плохиеБ.length===0&&состав.синтезБ.length===0
  &&состав.находок===14&&состав.уникН===14,состав);

 /* ── 3–6. Досье ── */
 const досье=await page.evaluate(()=>{
  const поля=["геометрия","акустика","ресурсы","твари","жители","ловушки",
   "тайников","дверей","ключи","миниБосс","стражПерехода","добыча","родПодземелья"];
  const a=floorDossier(1000,1000,12,"cave_entrance");
  const b=floorDossier(1000,1000,12,"cave_entrance");
  const c=floorDossier(1000,1000,13,"cave_entrance");
  const d=floorDossier(3000,3000,12,"cave_entrance");
  const пустые=a?поля.filter(p=>a[p]===undefined||a[p]===null||a[p]===""):поля;
  const было=G.place;
  floorDossier(2000,2000,30,"cave_entrance");
  const вернулись=G.place===было;
  return {полей:поля.length,пустые,
   тотЖе:JSON.stringify(a)===JSON.stringify(b),
   соседний:!!(a&&c&&(a.добыча!==c.добыча||a.жители!==c.жители||a.миниБосс!==c.миниБосс)),
   другаяШахта:!!(a&&d&&(a.добыча!==d.добыча||a.родПодземелья!==d.родПодземелья||a.геометрия!==d.геометрия)),
   вернулись,тайников:a?a.тайников:-1,дверей:a?a.дверей:-1};});
 check('у досье все тринадцать свойств, и ни одно не пустое',
  досье.полей===13&&досье.пустые.length===0,досье);
 check('досье выводится, а не хранится: тот же ярус даёт то же самое, соседний и другая шахта — другое',
  досье.тотЖе&&досье.соседний&&досье.другаяШахта,досье);
 check('досье не оставляет игрока стоящим на чужом ярусе',досье.вернулись,досье);
 check('тайники и двери считаются по самому ярусу, а не назначаются',
  досье.тайников>=0&&досье.дверей>=0&&(досье.тайников+досье.дверей)>0,досье);

 /* ── 8–10. Населённость и боссы ── */
 const населённость=await page.evaluate(()=>{
  let верх=0,низ=0,сБоссом=0,доТретьего=0;
  for(let d=1;d<=40;d++)if(floorFolk(1000,1000,d))верх++;
  for(let d=61;d<=100;d++)if(floorFolk(1000,1000,d))низ++;
  for(let d=1;d<=100;d++){
   const b=floorBoss(1000,1000,d);
   if(b)сБоссом++;
   if(b&&d<3)доТретьего++;}
  /* Ни один род не уходит глубже своего предела — проверяем на четырёх
     шахтах по сто ярусов каждая. */
  const глубже=[];
  const предел={};
  FLOOR_FOLK.forEach(f=>{предел[f.id]=f.до;});
  for(let bx=1000;bx<=4000;bx+=1000)
   for(let d=1;d<=100;d++){
    const x=floorFolk(bx,bx,d);
    if(x&&d>предел[x.id])глубже.push(x.id+"@"+d);}
  return {верх,низ,сБоссом,доТретьего,глубже:глубже.slice(0,4)};});
 check('жители есть не на всяком ярусе, и глубже их заметно реже',
  населённость.верх>0&&населённость.верх<40&&населённость.низ<населённость.верх,населённость);
 check('ни один род жителей не уходит глубже своего предела',
  населённость.глубже.length===0,населённость);
 check('мини-босс есть не на всяком ярусе и не появляется раньше третьего',
  населённость.сБоссом>0&&населённость.сБоссом<100&&населённость.доТретьего===0,населённость);

 /* ── 11–13. Слова ── */
 const слова=await page.evaluate(()=>{
  /* Ярус с мини-боссом — чтобы в строке было и то, и другое. */
  let d=-1;
  for(let k=3;k<=100&&d<0;k++)if(floorBoss(1000,1000,k))d=k;
  const s=floorLine(1000,1000,d,"cave_entrance");
  const f=floorDossier(1000,1000,d,"cave_entrance");
  /* Вехи: на десятом узел, на двадцать пятом усиленный страж. */
  const в10=floorDossier(1000,1000,10,"cave_entrance").веха;
  const в25=floorDossier(1000,1000,25,"cave_entrance").веха;
  const в11=floorDossier(1000,1000,11,"cave_entrance").веха;
  return {d,длина:s.length,
   естьГеометрия:/Геометрия: /.test(s),естьАкустика:/Акустика: /.test(s),
   естьРесурсы:/Ресурсы: /.test(s),естьТвари:/Твари: /.test(s),
   естьЖители:/Жители: /.test(s),естьЛовушки:/Ловушки: /.test(s),
   естьТайники:/Тайников \d+, дверей \d+/.test(s),естьКлючи:/ключ|запирать/.test(s),
   естьБосс:/Мини-босс: /.test(s),естьСтраж:/Хранитель перехода: /.test(s),
   естьДобыча:/Своя добыча яруса: /.test(s),
   боссНеСтраж:f.миниБосс!==f.стражПерехода,
   в10,в25,в11};});
 check('строка досье называет все тринадцать свойств, и мини-босс со стражем перехода — разные вещи',
  слова.естьГеометрия&&слова.естьАкустика&&слова.естьРесурсы&&слова.естьТвари
  &&слова.естьЖители&&слова.естьЛовушки&&слова.естьТайники&&слова.естьКлючи
  &&слова.естьБосс&&слова.естьСтраж&&слова.естьДобыча&&слова.боссНеСтраж,слова);
 check('веха ставится там, где ей положено: на десятом узел, на двадцать пятом усиленный страж, на одиннадцатом ничего',
  !!слова.в10&&!!слова.в25&&слова.в11===null,слова);

 /* ── 14. Команда и кнопка ── */
 const дверь=await page.evaluate(()=>{
  G.place=null;SAID.length=0;
  CMD.floor();
  const наверху=(SAID[SAID.length-1]||"");
  G.place={kind:"dungeon",bx:1000,by:1000,stype:"cave_entrance",depth:7,x:1,y:1};
  SAID.length=0;
  CMD.floor();
  const внизу=(SAID[SAID.length-1]||"");
  const тут=floorHere();
  G.place=null;
  return {наверху:наверху.slice(0,60),внизу:внизу.slice(0,60),
   естьТут:!!тут,глубина:тут?тут.глубина:-1,
   кнопка:JSON.stringify(AM_GROUPS).indexOf('"floor"')>0,
   команда:typeof CMD.floor==="function"};});
 check('команда и кнопка есть: в подземелье досье читается, наверху игра прямо говорит, что ярусов здесь нет',
  дверь.команда&&дверь.кнопка&&/ярусов нет/.test(дверь.наверху)
  &&/^Ярус 7/.test(дверь.внизу)&&дверь.естьТут&&дверь.глубина===7,дверь);

 /* ── 15. Самопроверка, модуль, глава ── */
 const свод=await page.evaluate(()=>{
  const rows=worldSelfCheck();
  const r=rows.find(x=>x.id==="floors13");
  const m=Modules.get("FLOORS");
  return {есть:!!r,ok:r?r.ok:false,
   плохие:rows.filter(x=>!x.ok).map(x=>x.id),
   модуль:!!m&&m.folk.length===12&&m.bosses.length===14&&m.prizes.length===14
    &&typeof m.at==="function"&&typeof m.here==="function"&&typeof m.line==="function",
   текст:m?m.text():"",
   глава:GUIDE.some(g=>/Глава 89\. Досье яруса/.test(g.title)&&g.body.length>=5)};});
 check('самопроверка держит строку floors13, модуль FLOORS отвечает, глава 89 на месте',
  свод.есть&&свод.ok&&свод.модуль&&свод.глава&&свод.текст.length>40,свод);
 check('ни одна другая строка самопроверки не покраснела',свод.плохие.length===0,свод.плохие);

 const корень=path.join(__dirname,'..');
 const readme=fs.readFileSync(path.join(корень,'README.md'),'utf8');
 const мир=fs.readFileSync(path.join(корень,'docs','МИР.md'),'utf8');
 check('README и docs/МИР.md описывают досье яруса',
  /Досье яруса/i.test(readme)&&/двенадцать родов/i.test(readme)
  &&/§19/.test(мир)&&/FLOOR_FOLK/.test(мир),
  {readme:/Досье яруса/i.test(readme),docs:/FLOOR_FOLK/.test(мир)});

 check('страница не бросила ни одной ошибки',errors.length===0,errors.slice(0,3));

 await browser.close();
 results.forEach(r=>console.log(r));
 const fail=results.filter(r=>r.startsWith('FAIL')).length;
 console.log(`\nИТОГО: ${results.length-fail} прошло, ${fail} провалено.`);
 process.exit(fail?1:0);
})();
