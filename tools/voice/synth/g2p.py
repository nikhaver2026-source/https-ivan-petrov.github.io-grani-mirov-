#!/usr/bin/env python3.13
"""g2p.py — русская транскрипция слова по правилам (для подбора частей слов по звукам, а не по буквам).
Звук — одна буква-код: гласные под ударением — заглавные (А О У Ы Э И), безударные — строчные с редукцией
(о→а, е/я→и после мягких, а→и после мягких); мягкие согласные — со знаком «'» как отдельный признак (для сравнения
берётся пара буква+мягкость, сведённая в один код); й — «j»; оглушение на конце и перед глухими, озвончение перед звонкими.
Ударение — словарь Koziev/NLP_Datasets all_accents (engine.ударение).
Выход: список (звук, номер буквы слова), чтобы время букв переводилось во время звуков."""
import sys
sys.path.insert(0, "/root/S/us2")

ГЛ = set("аеёиоуыэюя")
ЙОТ = {"е": "э", "ё": "о", "ю": "у", "я": "а"}
ВСЕГДА_ТВЁРД = set("жшц")
ВСЕГДА_МЯГК = set("чщй")
ЗВОНК = {"б": "п", "в": "ф", "г": "к", "д": "т", "ж": "ш", "з": "с"}
ГЛУХ = {v: k for k, v in ЗВОНК.items()}
ГЛУХИЕ = set("пфктшсхцчщ")
ЗВОНКИЕ_ШУМН = set("бгдзж")          # «в» не озвончает предыдущий
МЯГК_КОД = {"б": "Б", "в": "В", "г": "Г", "д": "Д", "з": "З", "к": "К", "л": "Л", "м": "М", "н": "Н", "п": "П", "р": "Р",
            "с": "С", "т": "Т", "ф": "Ф", "х": "Х"}   # мягкий согласный — свой код


def транскрипция(слово, уд=None):
    if уд is None:
        import engine as E
        уд = E.ударение(слово.lower().replace("ё", "е"))
    w = слово.lower().replace("ё", "е") if уд < 0 or слово[уд] != "ё" else слово.lower()
    out = []   # (код, номер буквы)
    n = len(w)
    for i, ch in enumerate(w):
        пред = w[i - 1] if i else ""
        след = w[i + 1] if i + 1 < n else ""
        if ch in "ьъ": continue
        if ch in ГЛ:
            ударная = i == уд
            после_мягкого = bool(пред) and (пред not in ГЛ and пред not in "ъь" and пред not in ВСЕГДА_ТВЁРД) and ch in "еёюяи"
            if ch in ЙОТ and (i == 0 or (пред and (пред in ГЛ or пред in "ъь"))):
                out.append(("j", i)); после_мягкого = True
            база = ЙОТ.get(ch, ch)
            if ударная: код = {"а": "А", "о": "О", "у": "У", "ы": "Ы", "э": "Э", "и": "И"}[база]
            else:
                if база == "о": код = "а"
                elif база in "эа" and (после_мягкого or ch in "ея"): код = "и"
                elif база == "э" and пред in ВСЕГДА_ТВЁРД: код = "ы"
                elif база == "и" and пред in ВСЕГДА_ТВЁРД: код = "ы"
                else: код = база
            out.append((код, i)); continue
        if ch == "й": out.append(("j", i)); continue
        if ch not in "бвгджзклмнпрстфхцчшщ": continue
        c = ch
        # мягкость: перед е ё и ю я ь (кроме всегда твёрдых)
        мягкий = c in ВСЕГДА_МЯГК or (c not in ВСЕГДА_ТВЁРД and bool(след) and след in "еёиюяь")
        # оглушение на конце и перед глухими; озвончение перед звонкими шумными
        дальше = next((x for x in w[i + 1:] if x not in "ьъ"), "")
        if дальше and дальше not in "бвгджзклмнпрстфхцчшщй" and дальше not in ГЛ: дальше = ""
        if c in ЗВОНК and (дальше == "" or дальше in ГЛУХИЕ): c = ЗВОНК[c]
        elif c in ГЛУХ and дальше in ЗВОНКИЕ_ШУМН: c = ГЛУХ[c]
        код = МЯГК_КОД.get(c, c) if мягкий and c in МЯГК_КОД else c
        out.append((код, i))
    return out


def строка(слово, уд=None):
    return "".join(k for k, _ in транскрипция(слово, уд))


if __name__ == "__main__":
    for w in sys.argv[1:] or ["вода", "вагон", "исчезла", "перчатке", "наставника", "гостю", "ёлка", "сад", "просьба", "мёд", "зелья", "шестьдесят"]:
        print(w, "→", строка(w))
