#!/usr/bin/env python3.13
"""fon.py — произношение фразы для разметки звуков (и подбора частей слов по звукам).
Основа — g2p.транскрипция (редукция безударных, мягкость, оглушение на конце); поверх — правила живого
произношения: -тся/-ться → [ца], что → [што], -ого/-его → [ава/ива], сч → [щ], непроизносимые согласные
(стн, здн, вств, лнц, рдц), гк → [хк], сш/зш → [ш], сж/зж → [ж], двойные согласные — один звук;
на стыке слов — уподобление по звонкости (предлоги перед гласной и сонорным звонкость сохраняют).
Выход для слова: список (звук, номер буквы)."""
import sys, re
sys.path.insert(0, "/root/S/us2")
import g2p

ГЛАСНЫЕ_ЗВ = set("АОУЫЭИаоуыэи")
ЗВОНК_ШУМН = set("бгджзБГДЗ")           # звонкие шумные (кроме «в»), озвончают предыдущий
ГЛУХ_ШУМН = set("пфктшсхцчщПФКТСХ")
ПАРЫ = {"б": "п", "в": "ф", "г": "к", "д": "т", "ж": "ш", "з": "с", "Б": "П", "В": "Ф", "Г": "К", "Д": "Т", "З": "С"}
ПАРЫ_О = {v: k for k, v in ПАРЫ.items()}
ПРЕДЛОГИ = {"в", "к", "с", "из", "без", "от", "под", "над", "об", "перед", "через", "из-за", "из-под", "со", "во", "ко"}
ОГО_ИСКЛ = {"много", "немного", "строго", "нестрого", "дорого", "недорого", "убого", "полого", "отлого", "разлого", "ого", "лого"}
ОСОБЫЕ = {"что": "што", "чтобы": "штобы", "ничто": "ништо", "кое-что": "коешто", "конечно": "канешна", "скучно": "скушна",
          "нарочно": "нарошна", "яичница": "яишница", "пустячный": "пустяшный", "сегодня": "севодня", "сегодняшний": "севодняшний",
          "солнце": "сонце", "здравствуй": "здраствуй", "здравствуйте": "здраствуйте", "чувство": "чуство", "чувства": "чуства"}


_ЁЁ = None
def _ё(w):
    """Слово с «ё» на месте «е», если в текстах игры оно пишется через «ё» (словарь ударений «ё» не различает)."""
    global _ЁЁ
    if _ЁЁ is None:
        import json, os
        p = "/root/S/us2/dict/yo_words.json"
        сп = json.load(open(p, encoding="utf-8")) if os.path.exists(p) else []
        _ЁЁ = {x.replace("ё", "е"): x for x in сп}
        _ЁЁ.update({"еще": "ещё", "ее": "её", "нее": "неё", "мое": "моё", "твое": "твоё", "свое": "своё", "идет": "идёт"})
    return _ЁЁ.get(w, w)


def слово(w):
    """Произношение отдельного слова → [(звук, номер буквы)] (номер буквы — в исходном написании)."""
    w0 = w
    if w in ОСОБЫЕ:
        тр = g2p.транскрипция(ОСОБЫЕ[w])
        n = len(w0)
        return [(k, min(i, n - 1)) for k, i in тр]
    wё = _ё(w)
    if wё != w:
        import engine as E
        i = wё.find("ё"); тр = list(g2p.транскрипция(wё, i))
    else: тр = list(g2p.транскрипция(w))
    if not тр: return тр
    # -тся / -ться → [ца]
    if re.search(r"ть?ся$", w) and len(тр) >= 3:
        i_т = w.rfind("т"); i_с = w.rfind("с")
        тр = [(k, i) for k, i in тр if i != i_с]
        тр = [("ц", i) if i == i_т else (k, i) for k, i in тр]
        if тр[-1][1] == len(w) - 1: тр[-1] = ("а" if тр[-1][0] in "иэ" else тр[-1][0], тр[-1][1])
    # -ого / -его (окончание прилагательных и местоимений): г → в
    if len(w) > 3 and re.search(r"[ое]го$", w) and w not in ОГО_ИСКЛ:
        i_г = len(w) - 2; тр = [("в", i) if (i == i_г and k in "гкГК") else (k, i) for k, i in тр]
    # сч / зч → щ
    for m in re.finditer(r"[сз]ч", w):
        i0 = m.start(); тр = [(k, i) for k, i in тр if i != i0]; тр = [("щ", i) if i == i0 + 1 else (k, i) for k, i in тр]
    # непроизносимые: стн, здн, стл (т/д выпадает), вств (первое в), лнц (л), рдц (д)
    for шаблон, выпад in (("стн", 1), ("здн", 1), ("стл", 1), ("вств", 0), ("лнц", 0), ("рдц", 1)):
        for m in re.finditer(шаблон, w):
            i0 = m.start() + выпад; тр = [(k, i) for k, i in тр if i != i0]
    # гк, гч → х
    for m in re.finditer(r"г[кч]", w):
        i0 = m.start(); тр = [("х", i) if i == i0 else (k, i) for k, i in тр]
    # сш, зш → ш ; сж, зж → ж (первый уподобляется и сливается)
    for m in re.finditer(r"[сз][шж]", w):
        i0 = m.start(); тр = [(k, i) for k, i in тр if i != i0]
    # двойные согласные — один звук
    out = []
    for k, i in тр:
        if out and out[-1][0] == k and k not in ГЛАСНЫЕ_ЗВ and k != "j": continue
        out.append((k, i))
    return out


def фраза(слова, паузы=None):
    """Произношение слов фразы с уподоблением на стыках. паузы[i] — есть ли пауза после слова i (тогда стыка нет)."""
    тр = [слово(w) for w in слова]
    for i in range(len(слова) - 1):
        if not тр[i] or not тр[i + 1]: continue
        if паузы and паузы[i]: continue
        посл, i_б = тр[i][-1]; след = тр[i + 1][0][0]
        исход = слова[i][-1]   # буква на конце
        if след in ЗВОНК_ШУМН:
            if посл in ПАРЫ_О: тр[i][-1] = (ПАРЫ_О[посл], i_б)
        elif след in ГЛУХ_ШУМН:
            if посл in ПАРЫ: тр[i][-1] = (ПАРЫ[посл], i_б)
        elif слова[i] in ПРЕДЛОГИ:
            # перед гласной, сонорным, «в», «й» предлог звонкость сохраняет: «в окне» [в], «из окна» [из]
            if посл in ПАРЫ_О and исход in "бвгджз": тр[i][-1] = (ПАРЫ_О[посл], i_б)
        # одинаковые звуки на стыке («в водах», «с собой») — один долгий: оставляем оба (разметка разделит)
    return тр


