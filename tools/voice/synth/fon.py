    for t in sys.argv[1:] or ["учатся у наставника", "в окне", "из окна", "в сторону", "без дела", "что это", "много его",
                              "счастье", "солнце", "лёгкий путь", "вход", "сжечь", "касса"]:
        ws = t.replace("ё", "е").split()
        print(t, "→", " | ".join("".join(k for k, _ in x) for x in фраза(ws)))
