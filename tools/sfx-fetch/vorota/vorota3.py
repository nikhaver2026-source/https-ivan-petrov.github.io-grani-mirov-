def петля(x, раз, перекр=0.12):
    """повторить отрезок раз подряд с плавным перекрытием"""
    n = int(перекр * SR); y = x.copy()
    for _ in range(раз - 1):
        a = y[-n:] * np.cos(np.linspace(0, np.pi / 2, n)) ** 2 + x[:n] * np.sin(np.linspace(0, np.pi / 2, n)) ** 2
        y = np.concatenate([y[:-n], a, x[n:]])
    return y

