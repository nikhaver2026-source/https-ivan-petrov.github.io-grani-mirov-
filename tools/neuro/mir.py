    def _ключ(s, ц):
        if isinstance(ц, dict): return ц.get("имя") or ц.get("текст", "")[:40]
        if isinstance(ц, tuple): return "|".join(sorted(x["имя"] for x in ц))
        return ""
    def _можно(s, e, ц):
        k = (e, s._ключ(ц)); был = s.было.get(k)
        if был is None: return True
        if e in s.ОДНАЖДЫ: return False
        return s.год - был >= s.ПЕРЕРЫВ.get(e, 0)

    # ── что возможно сейчас: для каждого события — список целей ──
    def возможные(s):
        вoz = s._возможные()
        return {e: [ц for ц in v if s._можно(e, ц)] for e, v in вoz.items() if any(s._можно(e, ц) for ц in v)}
    def _возможные(s):
        R = s.R; б = s.живые(s.боги); вoz = {}
        слабые = [x for x in б if x["вера"] < 0.2]
        вoz["вера_растёт"] = б; вoz["вера_угасает"] = б
        # (18) Учитель: «боги гибнут внезапно, ни разу не упомянутые» — падению предшествует завязка в летописи за 20 лет:
        # угасание веры или пророчество о закате этого бога
