    def признаки(s):
        б = s.живые(s.боги); жд = s.живые(s.державы, "жива")
        гист = collections.Counter(z["событие"] for z in s.летопись[-20:])
        f = [len(б) / 40, sum(x["вера"] for x in б) / max(1, len(б)), sum(1 for x in б if x["вера"] < 0.12) / 10,
             sum(1 for x in s.боги if not x["жив"]) / 20, len(жд) / 10, sum(len(д["войны"]) for д in жд) / 20,
             len(s.живые(s.города)) / 40, sum(len(р["подземелья"]) for р in s.регионы) / 40, len(s.живые(s.твари)) / 40,
             sum(т["числ"] for т in s.живые(s.твари)) / 20, sum(1 for т in s.твари if т.get("разумна")) / 10,
             len(s.артефакты) / 30, sum(1 for г in s.грани if г["открыта"]) / 10, len(s.регионы) / 80,
             len(s.персонажи) / 30, len(s.мифы) / 20, len(s.объекты) / 40, s.год / 400]
        f += [гист[e] / 5 for e in СОБЫТИЯ]
        return f

