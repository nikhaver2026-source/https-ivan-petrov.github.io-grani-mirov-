def женское(имя):
    """род по имени: первое слово на -а/-я (Лиса, Росана, Нерея) — женский"""
    w = (имя or "").split()
    if not w: return False
    х = w[0].lower()
    return х.endswith(("а", "я")) and not х.endswith(("ья", "ия")) or х.endswith(("ия", "ья")) and len(w) > 1 and w[1].lower().endswith(("ая", "яя"))

def гл(имя, м, ж): return ж if женское(имя) else м

