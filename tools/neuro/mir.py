def женское(имя):
    """род по имени: первое слово на -а/-я (Лиса, Росана, Нерея, Шептунья, Донная Тишь) — женский;
    мужские имена на -а/-я (Илья, Фома) — по списку"""
    w = (имя or "").split()
    if not w: return False
    х = w[0].lower().strip("«»\"")
    return х.endswith(("а", "я")) and х not in МУЖСКИЕ_НА_А

МН_ИСКЛ = {"луга": "мн", "подземья": "мн", "джунгли": "мн"}
def род_места(фраза):
    """род названия места или края: «м», «ж», «с» или «мн» (лес, пустыня, озеро, горы; древний лес, магическая
    пустошь, заброшенные ходы, устье реки)"""
    w = (фраза or "").lower().split()
    if not w: return "м"
    п = w[0]
    if п in МН_ИСКЛ: return МН_ИСКЛ[п]
    for конец, р in (("ые", "мн"), ("ие", "мн"), ("ый", "м"), ("ий", "м"), ("ой", "м"), ("ая", "ж"), ("яя", "ж"), ("ое", "с"), ("ее", "с")):
        if п.endswith(конец) and len(w) > 1: return р
    if п.endswith(("ы", "и")): return "мн"
    if п.endswith(("а", "я", "ь")): return "ж"
    if п.endswith(("о", "е", "ё")): return "с"
    return "м"
def был(фраза): return {"м": "был", "ж": "была", "с": "было", "мн": "были"}[род_места(фраза)]

