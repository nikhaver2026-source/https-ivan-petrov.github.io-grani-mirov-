    def _естественный_ход(s):
        """медленные силы мира между событиями: вера оседает, твари множатся, державы крепнут или слабеют"""
        R = s.R
        for б in s.живые(s.боги):
            народ = sum(н["численность"] for н in s.народы if н["бог"] == б["имя"]); храмы = sum(1 for г in s.живые(s.города) if г["храм"] == б["имя"])
            б["вера"] = max(0, min(1, б["вера"] + 0.004 * (народ + храмы) - 0.012))
        for т in s.живые(s.твари): т["числ"] = max(0, min(1, т["числ"] + R.uniform(-0.02, 0.025)))
        for д in s.живые(s.державы, "жива"): д["сила"] = max(0, min(1, д["сила"] + 0.01 * len(д["города"]) - 0.01 * len(д["войны"]) - 0.005))

