"""zhivoy.py — Живой мир: все сети Режиссёра вместе (в игру не входит).

Сердце мира выбирает, что случится; Летописец даёт имя новому (несколько вариантов — Судья оставляет лучший, повторов
нет); Мастер свойств даёт числа и признаки всему новому — тварям, растениям, землям, богам, городам, людям,
подземельям, находкам — и подбирает их по месту: тварь живёт в землях своего края, у города ремесло по его земле,
у героя смелый нрав, у пророка чуткий. Вещь собирает составитель из частей игры, ранг — по силе творца.
На выходе — летопись мира за заданное число лет (Markdown) и опись всего нового, что мир породил.

  python3 zhivoy.py <папка данных> [лет] [зерно] [файл вывода .md]
"""
import sys, os, json, random, collections
import torch
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import mir as M, serdce as S

РОД_ЛОВУШКИ = {"grav": "тяжести", "illusion": "морока", "light": "света", "living": "живая", "magic": "магическая", "mech": "механическая",
               "poison": "ядовитая", "sound": "звука", "space": "пространства", "time": "времени"}
ГРУБЫЕ = {"cave": "пещеры", "road": "дороги", "coast": "побережье", "desert": "пустыня", "forest": "лес", "mountains": "горы", "plains": "равнины", "swamp": "болото"}

def по_русски(T, мир, t, g):
    """порождённое Мастером — словами игры: края по-русски, твари по именам, ловушка — сродни настоящей"""
    земли = lambda сп: [ГРУБЫЕ.get(x, мир.биом_имя.get(x, x)) for x in (сп or [])]
    if t == "MONSTERS":
        return {"уровни": f"{g['min']}–{g['max']}", "нрав": g.get("нрав"), "охотится": {"ночь": "ночью", "день": "днём"}.get(g.get("часы"), g.get("часы")),
                "водится": земли(g.get("biomes"))}
    if t == "FINDS": return {"вес": g["вес"], "встречается": земли(g.get("где"))}
    if t == "CITY_TRADES": return {"земли": земли(g.get("земли")), "товар": g.get("товар"), "нужда": g.get("нужда")}
    if t == "TRAPS":
        сх = min(T.get("TRAPS", []), key=lambda x: (x["род"] != g["род"]) * 2 + (x["вид"] != g["вид"]) + abs(x["урон"] - g["урон"]) / 20)
        return f"{РОД_ЛОВУШКИ.get(g['род'], g['род'])} ({g['вид']}), урон {g['урон']} — сродни «{сх['n']}»"
    return g

def имена_по_id(T):
    имена = {}
    for k in ("MONSTERS", "DARK_MONSTERS", "SEA_MONSTERS", "RACES_DB"):
        for r in T.get(k, []):
            if isinstance(r, dict) and r.get("id") and r.get("n"): имена.setdefault(r["id"], r["n"])
    return имена

def свойства_нового(мастер, T, мир, e, ц, R, базы):
    """что Мастер скажет о новом, рождённом событием e (цель ц); None — событие ничего не породило"""
    import master as МС
    def база(край):
        рег = next((р for р in мир.регионы if р["имя"] == край), None) if isinstance(край, str) else край
        return базы.get(рег["биом"], "plains") if рег else "plains"
    def по_земле(t, поле, край):
        б = база(край); return по_русски(T, мир, t, МС.подобрать(мастер, t, lambda g: (б in (g.get(поле) or [])) + R.random() * 0.01))
    if e == "тварь_пришла": return мир.твари[-1]["имя"], по_земле("MONSTERS", "biomes", ц)
    if e == "ресурс_открыт": return ц["ресурсы"][-1], мастер.породить("PLANTS", 1)[0]
    if e == "земля_поднялась": return мир.регионы[-1]["имя"], мастер.породить("REGIONS", 1)[0]
    if "бог" in мир.летопись[-1]["след"]:
        return мир.боги[-1]["имя"], мастер.породить("LESSER_GODS", 1)[0]
    if e == "город_основан":
        г = мир.города[-1]; return г["имя"], по_земле("CITY_TRADES", "земли", г["регион"])
    if e == "объект_появился": return мир.объекты[-1]["имя"], по_земле("FINDS", "где", ц)
    if e == "персонаж_пришёл":
        п = мир.персонажи[-1]; сп = мастер.спец["SOUL_CHARS"]["чис"]; вес = МС.НРАВ_РОЛИ.get(п["роль"], {})
        g = МС.подобрать(мастер, "SOUL_CHARS", lambda g: sum(w * (g[k] - сп[k][0]) / сп[k][1] for k, w in вес.items()))
        return п["имя"], {"нрав": МС.нрав_ближе(T, g), **g}
    if e == "подземелье_открыто":
        п = ц["подземелья"][-1]; вид = мастер.породить("DUNG_TYPES", 1)[0]; план = мастер.породить("DUNGEON_KINDS", 1)[0]
        лов = мастер.породить("TRAPS", 1)[0]; ид = имена_по_id(T)
        return п["имя"], {**вид, "план": {k.split(".")[1]: v for k, v in план.items() if k.startswith("план.") and v},
                          "твари": [ид.get(x, x) for x in план["твари"]], "добыча": план["добыча"], "ловушка": по_русски(T, мир, "TRAPS", лов)}
    if e == "артефакт_выкован":
        бог = "сфера" in ц; v = МС.вещь(T, мир.артефакты[-1]["сила"], "бог" if бог else "персонаж", ц.get("сфера") if бог else ц.get("роль"), R)
        return мир.артефакты[-1]["имя"], {k: x for k, x in v.items() if x}
    return None

СОБСТВЕННЫЕ = {"персонаж", "бог", "поселение", "подземелье", "земля", "грань", "тварь", "вещь", "миф"}

def имена(папка, R):
    """функция имени: Летописец пишет варианты, Судья выбирает; если сетей нет — None (мир даст заглушку)"""
    try:
        import letopisec as Л, sudya as СД
        os.environ.setdefault("LET_D", "192"); os.environ.setdefault("LET_L", "4")
        м, сл = Л.загрузить(папка)
    except Exception as e:
        print("Летописец не загружен:", e); return None, {}
    try: су, ссл = СД.загрузить(папка)
    except Exception: су = None
    корпус = [json.loads(l) for l in open(os.path.join(папка, "corpus.jsonl"), encoding="utf-8")]
    изв = collections.defaultdict(set)
    for z in корпус: изв[z["вид"]].add(z["имя"])
    опись = collections.defaultdict(list)
    def f(вид, черты=None):
        вид_л = {"поселение": "поселение", "подземелье": "подземелье", "тварь": "тварь", "вещь": "вещь", "ресурс": "ресурс",
                 "грань": "грань", "земля": "земля", "персонаж": "персонаж", "находка": "находка", "миф": "миф", "бог": "бог"}.get(вид, вид)
        вар = Л.писать(м, сл, вид_л, 4, None, изв[вид_л] | {n for n, _ in опись[вид_л]}, T=0.8)
        if not вар: return None
        if су: вар.sort(key=lambda x: -СД.оценка(су, ссл, вид_л, x[0], x[1]))
        имя, о = вар[0]
        if вид_л in СОБСТВЕННЫЕ: имя = имя[:1].upper() + имя[1:]  # имя собственное — с заглавной
        опись[вид_л].append((имя, о)); return имя
    return f, опись

def прогон(папка, лет=100, зерно=7, вывод=None):
    torch.set_num_threads(2); R = random.Random(зерно)
    T = json.load(open(os.path.join(папка, "world_tables.json"), encoding="utf-8"))
    f, опись = имена(папка, R)
    c = torch.load(os.path.join(папка, "serdce.pt")); сеть = S.Сердце(c["вход"]); S.загрузить_веса(сеть, c); сеть.eval()
    мастер = None
    try:
        import master as МС; мастер = МС.загрузить(папка)
    except Exception: pass
    мир = M.Мир(T, зерно, имена=f); игрок = S.новый_игрок(R)
    свойства = {}; базы = МС.базы_биомов(T) if мастер else {}
    with torch.no_grad():
        for _ in range(лет):
            возм = мир.возможные(); маска = torch.full((S.E,), float("-inf"))
            for e in возм: маска[M.СОБЫТИЯ.index(e)] = 0
            x = torch.tensor(мир.признаки() + игрок + [S.напряжение(мир)], dtype=torch.float32)
            h, логиты, _ = сеть(x.unsqueeze(0)); p = torch.softmax(логиты[0] + маска, -1); ei = int(torch.multinomial(p, 1)); e = M.СОБЫТИЯ[ei]
            цели = возм[e] if len(возм[e]) <= 24 else R.sample(возм[e], 24)
            чц = torch.tensor([S.черты_цели(ц, мир, ei) for ц in цели], dtype=torch.float32)
            ц = цели[int(torch.multinomial(torch.softmax(сеть.оценка_целей(h, ei, чц), -1), 1))]
            мир.шаг(e, ц)
            if мастер:
                н = свойства_нового(мастер, T, мир, e, ц, R, базы)
                if н: свойства[н[0]] = (len(мир.летопись) - 1, н[1])
    строки = [f"# Летопись мира за {лет} лет (зерно {зерно})", "",
              "Сердце мира выбирало события, Летописец давал имена новому, Судья отбирал лучшее, Мастер свойств — числа.", ""]
    при = {i: (имя, св) for имя, (i, св) in свойства.items()}
    def кратко(v):
        if isinstance(v, dict): return ", ".join(f"{k} {x}" for k, x in v.items())
        if isinstance(v, list): return ", ".join(map(str, v))
        return str(v)
    for i, z in enumerate(мир.летопись):
        доп = ""
        if i in при: доп = " — " + "; ".join(f"{k}: {кратко(vv)}" for k, vv in при[i][1].items() if vv not in (None, [], {}))
        строки.append(f"- **Год {z['год']}.** {z['текст']}{доп}")
    if опись:
        строки += ["", "## Новое, что породил мир", ""]
        for вид, сп in опись.items():
            строки.append(f"- **{вид}**: " + "; ".join(f"{n}" + (f" ({о[:80]})" if о else "") for n, о in сп))
    текст = "\n".join(строки) + "\n"
    if вывод: open(вывод, "w", encoding="utf-8").write(текст)
    print(текст)

if __name__ == "__main__":
    прогон(sys.argv[1], int(sys.argv[2]) if len(sys.argv) > 2 else 100, int(sys.argv[3]) if len(sys.argv) > 3 else 7, sys.argv[4] if len(sys.argv) > 4 else None)
