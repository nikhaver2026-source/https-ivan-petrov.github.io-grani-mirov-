"""zhivoy.py — Живой мир: все сети Режиссёра вместе (в игру не входит).

Сердце мира выбирает, что случится; Летописец даёт имя новому (десять вариантов, копии настоящих имён любого вида отброшены; лучший оставляет Мета-судья, а без него — Судья и Словник:
Словник снимает баллы за выдуманные слова в описательных именах; повторов нет); Мастер свойств даёт числа и признаки всему новому (твари, краю, богу и подземелью — ещё до имени: Летописец
пишет имя под черты, которые дал Мастер, — «нрав=нежить; biomes=cave») — тварям, растениям, землям, богам, городам, людям,
подземельям, находкам — и подбирает их по месту: тварь живёт в землях своего края, у города ремесло по его земле,
у героя смелый нрав, у пророка чуткий. Вещь собирает составитель из частей игры, ранг — по силе творца.
На выходе — летопись мира за заданное число лет (Markdown), разбитая на эпохи (эпоха начинается с большого события —
падения бога, открытия грани, распада державы, бедствия, восстания городов — и называется по нему), и опись всего
нового, что мир породил.

  python3 zhivoy.py <папка данных> [лет] [зерно] [файл вывода .md или .json]
"""
import sys, os, re, json, random, collections
import torch
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import mir as M, serdce as S

РОД_ЛОВУШКИ = {"grav": "тяжести", "illusion": "морока", "light": "света", "living": "живая", "magic": "магическая", "mech": "механическая",
               "poison": "ядовитая", "sound": "звука", "space": "пространства", "time": "времени"}
ГРУБЫЕ = {"cave": "пещеры", "road": "дороги", "coast": "побережье", "desert": "пустыня", "forest": "лес", "mountains": "горы", "plains": "равнины", "swamp": "болото"}

def по_русски(T, мир, t, g):
    """порождённое Мастером — словами игры: края по-русски, твари по именам, ловушка — сродни настоящей"""
    земли = lambda сп: [ГРУБЫЕ.get(x, мир.биом_имя.get(x, x)) for x in (сп or [])]
    if t == "MONSTERS":
        return {"уровни": f"{g['min']}–{g['max']}", "нрав": g.get("нрав"), "охотится": {"ночь": "ночью", "день": "днём"}.get(g.get("часы"), g.get("часы")),
                "водится": земли(g.get("biomes"))}
    if t == "FINDS": return {"вес": g["вес"], "встречается": земли(g.get("где"))}
    if t == "CITY_TRADES": return {"земли": земли(g.get("земли")), "товар": g.get("товар"), "нужда": g.get("нужда")}
    if t == "TRAPS":
        сх = min(T.get("TRAPS", []), key=lambda x: (x["род"] != g["род"]) * 2 + (x["вид"] != g["вид"]) + abs(x["урон"] - g["урон"]) / 20)
        return f"{РОД_ЛОВУШКИ.get(g['род'], g['род'])} ({g['вид']}), урон {g['урон']} — сродни «{сх['n']}»"
    return g

def имена_по_id(T):
    имена = {}
    for k in ("MONSTERS", "DARK_MONSTERS", "SEA_MONSTERS", "RACES_DB"):
        for r in T.get(k, []):
            if isinstance(r, dict) and r.get("id") and r.get("n"): имена.setdefault(r["id"], r["n"])
    return имена

def заготовка(мастер, T, мир, вид, черты, R, базы):
    """(Мастер → Летописец) свойства нового — до имени: Мастер порождает их по месту, а Летописец пишет имя под эти
    черты в том виде, как они стояли в его обучении («нрав=нежить; biomes=cave, swamp»). → ((таблица, свойства), строка черт)"""
    import master as МС
    край = dict(x.split("=", 1) for x in (черты or "").split(";") if "=" in x).get("край")
    рег = next((р for р in мир.регионы if р["имя"] == край), None); б = базы.get(рег["биом"], "plains") if рег else "plains"
    if вид == "тварь":
        g = МС.подобрать(мастер, "MONSTERS", lambda g: (б in (g.get("biomes") or [])) + R.random() * 0.01)
        return ("MONSTERS", g), "; ".join(x for x in (f"нрав={g['нрав']}" if g.get("нрав") else "", "biomes=" + ", ".join(g.get("biomes") or [])) if x)
    if вид == "земля":
        g = мастер.породить("REGIONS", 1)[0]
        return ("REGIONS", g), f"климат={g['климат']}; биомы={', '.join(g['биомы'])}; ресурс={g['ресурс']}; опасность={g['опасность']}"
    if вид == "бог":
        g = мастер.породить("LESSER_GODS", 1)[0]; return ("LESSER_GODS", g), f"тип={g['тип']}"
    if вид == "подземелье":
        g = мастер.породить("DUNG_TYPES", 1)[0]; return ("DUNG_TYPES", g), f"ресурс={g['ресурс']}"
    return None

def свойства_нового(мастер, T, мир, e, ц, R, базы, заготовки=None):
    """что Мастер скажет о новом, рождённом событием e (цель ц); None — событие ничего не породило"""
    import master as МС
    def база(край):
        рег = next((р for р in мир.регионы if р["имя"] == край), None) if isinstance(край, str) else край
        return базы.get(рег["биом"], "plains") if рег else "plains"
    def по_земле(t, поле, край):
        б = база(край); return по_русски(T, мир, t, МС.подобрать(мастер, t, lambda g: (б in (g.get(поле) or [])) + R.random() * 0.01))
    заготовки = заготовки or {}
    def готовое(имя, t): з = заготовки.pop(имя, None); return з[1] if з and з[0] == t else None
    if e == "тварь_пришла":
        имя = мир.твари[-1]["имя"]; g = готовое(имя, "MONSTERS")
        return имя, (по_русски(T, мир, "MONSTERS", g) if g else по_земле("MONSTERS", "biomes", ц))
    if e == "ресурс_открыт": return ц["ресурсы"][-1], мастер.породить("PLANTS", 1)[0]
    if e == "земля_поднялась":
        р = мир.регионы[-1]; g = готовое(р["имя"], "REGIONS") or мастер.породить("REGIONS", 1)[0]
        # новая земля живёт по своим свойствам: биом, климат и опасность — те, под которые написано имя
        р["биом"] = (g.get("биомы") or [р["биом"]])[0]; р["климат"] = g.get("климат") or ""; р["опасность"] = float(g.get("опасность") or 3)
        return р["имя"], g
    if "бог" in мир.летопись[-1]["след"]:
        имя = мир.боги[-1]["имя"]; return имя, готовое(имя, "LESSER_GODS") or мастер.породить("LESSER_GODS", 1)[0]
    if e == "город_основан":
        г = мир.города[-1]; return г["имя"], по_земле("CITY_TRADES", "земли", г["регион"])
    if e == "объект_появился": return мир.объекты[-1]["имя"], по_земле("FINDS", "где", ц)
    if e == "персонаж_пришёл":
        п = мир.персонажи[-1]; сп = мастер.спец["SOUL_CHARS"]["чис"]; вес = МС.НРАВ_РОЛИ.get(п["роль"], {})
        g = МС.подобрать(мастер, "SOUL_CHARS", lambda g: sum(w * (g[k] - сп[k][0]) / сп[k][1] for k, w in вес.items()))
        return п["имя"], {"нрав": МС.нрав_ближе(T, g), **g}
    if e == "подземелье_открыто":
        п = ц["подземелья"][-1]; вид = готовое(п["имя"], "DUNG_TYPES") or мастер.породить("DUNG_TYPES", 1)[0]; план = мастер.породить("DUNGEON_KINDS", 1)[0]
        лов = мастер.породить("TRAPS", 1)[0]; ид = имена_по_id(T)
        return п["имя"], {**вид, "план": {k.split(".")[1]: v for k, v in план.items() if k.startswith("план.") and v},
                          "твари": [ид.get(x, x) for x in план["твари"]], "добыча": план["добыча"], "ловушка": по_русски(T, мир, "TRAPS", лов)}
    if e == "артефакт_выкован":
        бог = "сфера" in ц; v = МС.вещь(T, мир.артефакты[-1]["сила"], "бог" if бог else "персонаж", ц.get("сфера") if бог else ц.get("роль"), R)
        return мир.артефакты[-1]["имя"], {k: x for k, x in v.items() if x}
    return None

СОБСТВЕННЫЕ = {"персонаж", "бог", "поселение", "подземелье", "земля", "грань", "тварь", "вещь", "миф"}

def годится(вид, имя):
    """форма имени: у имён собственных — похоже на имя (до четырёх слов, без запятых и скобок, не глагол в начале), у
    любых — не длиннее пяти слов и без служебных знаков («Вы и после {а} помните…» — не имя персонажа)"""
    import corpus as К
    if re.search(r"[{}<>\[\]|]", имя) or len(имя.split()) > 5: return False
    return К.похоже_на_имя(имя[:1].upper() + имя[1:]) if вид in К.ИМЕННЫЕ else True

def имена(папка, R):
    """функция имени: Летописец пишет варианты, Судья выбирает; если сетей нет — None (мир даст заглушку)"""
    try:
        import letopisec as Л, sudya as СД
        os.environ.setdefault("LET_D", "192"); os.environ.setdefault("LET_L", "4")
        м, сл = Л.загрузить(папка)
    except Exception as e:
        print("Летописец не загружен:", e); return None, {}
    try: су, ссл = СД.загрузить(папка)
    except Exception: су = None
    try:
        import slovnik as СН; сн = СН.построить(папка)
    except Exception: сн = None
    мета = СД.мета_загрузить(папка) if су else None  # Мета-судья (учился на оценках Учителя) — если есть, ранжирует он
    корпус = [json.loads(l) for l in open(os.path.join(папка, "corpus.jsonl"), encoding="utf-8")]
    изв = collections.defaultdict(set)
    for z in корпус: изв[z["вид"]].add(z["имя"])
    все_имена = {z["имя"].lower() for z in корпус}
    опись = collections.defaultdict(list)
    def f(вид, черты=None):
        вид_л = {"поселение": "поселение", "подземелье": "подземелье", "тварь": "тварь", "вещь": "вещь", "ресурс": "ресурс",
                 "грань": "грань", "земля": "земля", "персонаж": "персонаж", "находка": "находка", "миф": "миф", "бог": "бог",
                 "орден": "поселение"}.get(вид, вид)  # (17) у Летописца нет вида «орден» — имя по образцу поселений, в кавычках
        з = f.подготовка(вид, черты) if getattr(f, "подготовка", None) else None  # свойства от Мастера — до имени
        # нечёткий отсев — среди имён своего вида и уже порождённых; копии настоящих имён любого вида («Прибой» как тварь) —
        # точным совпадением (нечёткое сравнение со всеми пятью тысячами имён слишком медленно)
        вар = Л.писать(м, сл, вид_л, 10, з[1] if з else None, изв[вид_л] | {n for сп in опись.values() for n, _ in сп}, T=0.8)
        вар = [x for x in вар if x[0].lower() not in все_имена and годится(вид_л, x[0])]
        if not вар: return None
        # лучший вариант: оценка Судьи минус штраф Словника за выдуманные слова (в описательном имени — строже)
        if мета: вар.sort(key=lambda x: -мета(вид_л, x[0], x[1]))
        else: вар.sort(key=lambda x: -((СД.оценка(су, ссл, вид_л, x[0], x[1]) if су else 0.5) - (СН.штраф(сн, вид_л, x[0], x[1]) if сн else 0)))
        имя, о = вар[0]
        if вид_л in СОБСТВЕННЫЕ: имя = имя[:1].upper() + имя[1:]  # имя собственное — с заглавной
        опись[вид_л].append((имя, о))
        if з: f.заготовки[имя] = з[0]
        return имя
    f.заготовки = {}
    return f, опись

def имя_эпохи(z, мир):
    """название эпохи по событию, с которого она началась; None — событие не начинает эпоху"""
    e, п = z["событие"], z["причины"]; сл = z["след"]
    if e == "бог_падает": return f"Время павшего бога «{п[0]}»"
    if e in ("бог_наследник", "бог_апофеоз", "бог_из_грани", "бог_дух_места"): return f"Восход бога «{сл.get('бог', '')}»"
    if e == "грань_открылась": return f"Время грани «{сл.get('грань', '')}»"
    if e == "держава_распалась": return f"Смута после распада державы {п[0]}"
    if e == "бедствие": return f"Годы бедствия: {сл.get('бедствие', 'беда')} в краю «{п[0]}»"
    if e == "город_восстал": return "Время вольных городов"
    if e == "война" and len(п) == 2: return f"Война держав {п[0]} и {п[1]}"
    return None

def эпохи(мир, мин_лет=15):
    """летопись по эпохам: новая — с большого события, не раньше чем через мин_лет после начала прежней"""
    вывод = [["Начало", 1, []]]
    for i, z in enumerate(мир.летопись):
        н = имя_эпохи(z, мир)
        if н and z["год"] - вывод[-1][1] >= мин_лет: вывод.append([н, z["год"], []])
        вывод[-1][2].append(i)
    return вывод

def прогон(папка, лет=100, зерно=7, вывод=None):
    torch.set_num_threads(2); R = random.Random(зерно)
    T = json.load(open(os.path.join(папка, "world_tables.json"), encoding="utf-8"))
    f, опись = имена(папка, R)
    c = torch.load(os.path.join(папка, "serdce.pt")); сеть = S.сеть_из(c, T); сеть.eval()
    мастер = None
    try:
        import master as МС; мастер = МС.загрузить(папка)
    except Exception: pass
    мир = M.Мир(T, зерно, имена=f); игрок = S.новый_игрок(R)
    свойства = {}; базы = МС.базы_биомов(T) if мастер else {}
    if f and мастер: f.подготовка = lambda вид, черты: заготовка(мастер, T, мир, вид, черты, R, базы)
    with torch.no_grad():
        for _ in range(лет):
            возм = мир.возможные(); маска = torch.full((S.E,), float("-inf"))
            for e in возм: маска[M.СОБЫТИЯ.index(e)] = 0
            x = torch.tensor(мир.признаки() + игрок + [S.напряжение(мир)], dtype=torch.float32)
            h, логиты, _ = сеть(x.unsqueeze(0)); p = torch.softmax(логиты[0] + маска, -1); ei = int(torch.multinomial(p, 1)); e = M.СОБЫТИЯ[ei]
            цели = возм[e] if len(возм[e]) <= 24 else R.sample(возм[e], 24)
            чц = torch.tensor([S.черты_цели(ц, мир, ei) for ц in цели], dtype=torch.float32)
            ц = цели[int(torch.multinomial(torch.softmax(сеть.оценка_целей(h, ei, чц), -1), 1))]
            мир.шаг(e, ц)
            if мастер:
                н = свойства_нового(мастер, T, мир, e, ц, R, базы, f.заготовки if f else None)
                if н: свойства[н[0]] = (len(мир.летопись) - 1, н[1])
    строки = [f"# Летопись мира за {лет} лет (зерно {зерно})", "",
              "Сердце мира выбирало события, Летописец давал имена новому, Судья отбирал лучшее, Мастер свойств — числа.", ""]
    при = {i: (имя, св) for имя, (i, св) in свойства.items()}
    def кратко(v):
        if isinstance(v, dict): return ", ".join(f"{k} {x}" for k, x in v.items())
        if isinstance(v, list): return ", ".join(map(str, v))
        return str(v)
    эп = эпохи(мир)
    for j, (название, с, номера) in enumerate(эп):
        до = эп[j + 1][1] - 1 if j + 1 < len(эп) else мир.год
        строки += ["", f"## {название} (годы {с}–{до})", ""]
        for i in номера:
            z = мир.летопись[i]; доп = ""
            if i in при: доп = " — " + "; ".join(f"{k}: {кратко(vv)}" for k, vv in при[i][1].items() if vv not in (None, [], {}))
            строки.append(f"- **Год {z['год']}.** {z['текст']}{доп}")
    if опись:
        строки += ["", "## Новое, что породил мир", ""]
        for вид, сп in опись.items():
            строки.append(f"- **{вид}**: " + "; ".join(f"{n}" + (f" ({о[:80]})" if о else "") for n, о in сп))
    текст = "\n".join(строки) + "\n"
    if вывод and вывод.endswith(".json"):  # то же — данными: эпохи, события со свойствами, опись нового, итоги мира
        def чисто(v):
            if isinstance(v, dict): return {str(k): чисто(x) for k, x in v.items() if x not in (None, [], {})}
            if isinstance(v, (list, tuple)): return [чисто(x) for x in v]
            return v if isinstance(v, (int, float, str, bool)) or v is None else str(v)
        данные = {"лет": лет, "зерно": зерно,
                  "эпохи": [{"имя": н, "с": с, "до": (эп[j + 1][1] - 1 if j + 1 < len(эп) else мир.год),
                             "события": [{"год": мир.летопись[i]["год"], "событие": мир.летопись[i]["событие"], "текст": мир.летопись[i]["текст"],
                                          **({"свойства": чисто(при[i][1])} if i in при else {})} for i in номера]} for j, (н, с, номера) in enumerate(эп)],
                  "опись": {в: [{"имя": n, "о": о} for n, о in сп] for в, сп in опись.items()},
                  "итоги": {"богов живых": len(мир.живые(мир.боги)), "новых богов": sum(1 for b in мир.боги if b.get("род") == "новый"),
                            "держав": len(мир.живые(мир.державы, "жива")), "городов": len(мир.живые(мир.города)), "краёв": len(мир.регионы),
                            "подземелий": sum(len(р["подземелья"]) for р in мир.регионы), "граней открыто": sum(1 for г in мир.грани if г["открыта"]),
                            "персонажей живых": sum(1 for п in мир.персонажи if п["жив"]), "артефактов": len(мир.артефакты),
                            "мифов": len(мир.мифы), "орденов": sum(1 for о in мир.ордены if о["жив"]), "путей": sum(1 for п in мир.пути if п["жив"])}}
        json.dump(данные, open(вывод, "w", encoding="utf-8"), ensure_ascii=False, indent=1)
    elif вывод: open(вывод, "w", encoding="utf-8").write(текст)
    print(текст)

