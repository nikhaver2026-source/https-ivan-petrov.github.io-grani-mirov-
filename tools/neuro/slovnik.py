"""slovnik.py — Словник: проверка, из настоящих ли слов собрано имя (в игру не входит).

Летописец пишет по буквам и иногда сочиняет несуществующие слова: «Выдубранный замедленный трутный», «прястая вас».
Для имён собственных (бог, персонаж, город, грань) выдуманное слово — норма: Мортана, Скиада. Для описательных имён
(тварь, ресурс, вещь, находка, край, подземелье, миф) слова должны быть русскими: «Барханный баран», «Медный
верблюд». Словник — все слова русского текста игры и таблиц мира (имена и описания) с основами: слово знакомо, если
оно есть в тексте или у него та же основа, что у знакомого (без последних 1–2 букв, основа не короче пяти):
«замедленный» знаком по «замедленная», «немная» — нет. И согласование: прилагательное и существительное за ним
одного рода («Медный верблюд», но не «Ветреный Темны» или «Старый Края»).

  python3 slovnik.py check <папка данных> <фраза>            — доля незнакомых слов
  python3 slovnik.py eval  <папка данных> [на вид]           — у Летописца: доля описательных имён без выдуманных слов
"""
import sys, os, re, json, collections

ОПИСАТЕЛЬНЫЕ = {"тварь", "ресурс", "вещь", "находка", "земля", "подземелье", "миф", "растение", "зелье", "здание", "чары", "зверь"}
СЛОВО = re.compile(r"[а-яё]+")

class Словник:
    def __init__(s, слова):
        s.слова = set(слова); s.основы = set()
        for w in s.слова:
            for k in range(0, 3):
                if len(w) - k >= 5: s.основы.add(w[:len(w) - k])
    def знакомо(s, w):
        w = w.lower()
        if len(w) <= 3 or w in s.слова: return True
        return any(w[:len(w) - k] in s.основы for k in range(0, 3) if len(w) - k >= 5)
    def незнакомые(s, фраза): return [w for w in СЛОВО.findall((фраза or "").lower()) if not s.знакомо(w)]
    def доля(s, фраза):
        ws = СЛОВО.findall((фраза or "").lower())
        return sum(1 for w in ws if not s.знакомо(w)) / len(ws) if ws else 0.0

# род прилагательного по окончанию (именительный падеж; «-ие» не берётся — бывает и у существительных: сияние)
РОД_ПРИЛ = (("ый", "м"), ("ий", "м"), ("ой", "м"), ("ая", "ж"), ("яя", "ж"), ("ое", "с"), ("ее", "с"), ("ые", "мн"))
СР_НА_МЯ = {"имя", "время", "пламя", "знамя", "семя", "темя", "бремя", "стремя", "вымя", "племя"}
def род_сущ(w):
    """род существительного по окончанию; None — не ясно (на -ь, или похоже на прилагательное)"""
    if len(w) >= 5 and (any(w.endswith(к) for к, _ in РОД_ПРИЛ) or w.endswith("ие")): return None  # «края», «стая» — не прилагательные
    if w in СР_НА_МЯ: return "с"
    if w.endswith(("а", "я")): return "ж"
    if w.endswith(("о", "е", "ё")): return "с"
    if w.endswith(("ы", "и")): return "мн"
    if w.endswith("ь"): return None
    return "м"

def несогласие(имя):
    """прилагательное и следом существительное разного рода: «Ветреный Темны», «Старый Края» — 1, иначе 0"""
    ws = СЛОВО.findall((имя or "").lower())
    for a, b in zip(ws, ws[1:]):
        ра = next((р for к, р in РОД_ПРИЛ if a.endswith(к)), None) if len(a) >= 5 else None
        рб = род_сущ(b)
        if ра and рб and ра != рб: return 1
    return 0

def построить(папка):
    слова = collections.Counter()
    пт = os.path.join(папка, "text.txt")
    if os.path.exists(пт):
        for l in open(пт, encoding="utf-8"): слова.update(СЛОВО.findall(l.lower()))
    for l in open(os.path.join(папка, "corpus.jsonl"), encoding="utf-8"):
        z = json.loads(l); слова.update(СЛОВО.findall((z.get("имя", "") + " " + z.get("о", "")).lower()))
    return Словник(слова)

def штраф(сн, вид, имя, о=""):
    """сколько снять с оценки Судьи: за выдуманные слова в описательном имени — много, в описании — меньше"""
    в_имени = сн.доля(имя) if вид in ОПИСАТЕЛЬНЫЕ else 0.3 * сн.доля(имя)
    return 0.6 * в_имени + 0.3 * сн.доля(о) + 0.3 * несогласие(имя)

if __name__ == "__main__":
    cmd, папка = sys.argv[1], sys.argv[2]; сн = построить(папка)
    if cmd == "check":
        ф = " ".join(sys.argv[3:]); print(f"незнакомых {сн.доля(ф):.2f}: {сн.незнакомые(ф)}; несогласие {несогласие(ф)}")
    else:
        import torch; sys.path.insert(0, os.path.dirname(os.path.abspath(__file__))); import letopisec as Л
        torch.set_num_threads(2); torch.manual_seed(1); м, сл = Л.загрузить(папка); n = int(sys.argv[3]) if len(sys.argv) > 3 else 12
        корпус = [json.loads(l) for l in open(os.path.join(папка, "corpus.jsonl"), encoding="utf-8")]
        чистых = всего = 0; чистых_о = всего_о = 0
        for в in sorted(ОПИСАТЕЛЬНЫЕ & set(Л.ВИДЫ)):
            изв = {z["имя"] for z in корпус if z["вид"] == в}; р = Л.писать(м, сл, в, n, известные=изв, T=0.8)
            ч = sum(1 for имя, _ in р if сн.доля(имя) == 0 and not несогласие(имя)); чистых += ч; всего += len(р)
            чо = sum(1 for _, о in р if о and сн.доля(о) == 0); чистых_о += чо; всего_о += sum(1 for _, о in р if о)
            print(f"{в}: без выдуманных слов и несогласия {ч}/{len(р)}; пример: " + " | ".join(n for n, _ in р[:4]), flush=True)
        print(f"итого: имена без выдуманных слов и несогласия {чистых / max(1, всего):.2f}, описания без выдуманных слов {чистых_о / max(1, всего_о):.2f}")
