"""uchitel.py — Учитель: внешняя оценка Режиссёра большой языковой моделью (Gemini) (в игру не входит).

Свои мерила Сердца мира (связность, новизна, состав) считает сам симулятор — по ним сеть и учится, и по ним же её
проверять мало. Учитель смотрит со стороны, как читатель:
  летописи — две летописи одного и того же мира (тот же старт), написанные разными кругами Сердца, Gemini читает
             вслепую (порядок случайный) и оценивает: причинность, интерес, разнообразие, правдоподобие мира (1–10),
             и какая лучше;
  имена    — выдумки Летописца (вид, имя, описание) Gemini оценивает по пятибалльной шкале: грамотный ли русский,
             подходит ли имя виду, звучит ли как имя в мире тёмного фэнтези, нет ли бессмыслицы. Оценки идут в
             обучение Судьи (sudya.py): хорошие выдумки — к настоящим, плохие — к браку;
  критика  — слабые места летописей одного круга (род слабости, годы, какой закон мира её исправит) — сырьё для
             законов симулятора и награды следующего круга.

Ключи — из переменной окружения GEMINI_API_KEYS (через запятую), нигде не печатаются.

  python3 uchitel.py letopisi <папка данных> <снимок А> <снимок Б> [миров] [лет]   — попарное сравнение кругов
  python3 uchitel.py imena <файл выдумок вид\\tимя\\tо> <файл оценок .jsonl>          — оценки выдумкам
  python3 uchitel.py kritika <папка данных> <снимок> [миров] [лет]                  — слабые места летописей круга
  python3 uchitel.py obrazcy <корпус .jsonl> <выход .jsonl> <виды через запятую> [на вид] [зерно] — учебные образцы для Летописца
"""
import sys, os, json, random, time, urllib.request, urllib.error
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

МОДЕЛИ = os.environ.get("UCH_MODELS", "gemini-3.8-flash,gemini-3.7-flash,gemini-3.6-flash,gemini-3.5-flash").split(",")
КЛЮЧИ = [k.strip() for k in os.environ.get("GEMINI_API_KEYS", "").replace(" ", ",").split(",") if k.strip()]
_к = [0]; _мёртвые = set()

def спросить(текст, t=0.2):
    """запрос к Gemini с ответом JSON; ключи по кругу, суточная квота ключа — ключ откладывается"""
    if not КЛЮЧИ and os.environ.get("UCH_GEM"):  # нет переменной — общий модуль вызова Gemini рабочей папки (тот же, что у записи голосов)
        sys.path.insert(0, os.environ["UCH_GEM"]); import gem
        о = gem.ask([("text", текст)], temp=t); о.pop("_model", None)
        return {"ошибка": о["error"]} if "error" in о else о
    if not КЛЮЧИ: raise SystemExit("нет ключей: задайте GEMINI_API_KEYS")
    тело = {"contents": [{"parts": [{"text": текст}]}], "generationConfig": {"temperature": t, "responseMimeType": "application/json"}}
    посл = None
    for попытка in range(6):
        for м in МОДЕЛИ:
            for i in range(len(КЛЮЧИ)):
                к = КЛЮЧИ[(_к[0] + i) % len(КЛЮЧИ)]
                if (м, к) in _мёртвые: continue
                req = urllib.request.Request(f"https://generativelanguage.googleapis.com/v1beta/models/{м}:generateContent",
                                             data=json.dumps(тело).encode(), headers={"x-goog-api-key": к, "Content-Type": "application/json"})
                try:
                    with urllib.request.urlopen(req, timeout=240) as r: d = json.loads(r.read())
                    т = d["candidates"][0]["content"]["parts"][0]["text"]; _к[0] = (_к[0] + i + 1) % len(КЛЮЧИ)
                    return json.loads(т[min([x for x in (т.find("{"), т.find("[")) if x >= 0]):])
                except urllib.error.HTTPError as e:
                    посл = f"{м}: HTTP {e.code}"
                    if e.code == 429:
                        try:
                            if "PerDay" in e.read().decode(): _мёртвые.add((м, к))
                        except Exception: pass
                except Exception as e: посл = f"{м}: {str(e)[:80]}"
        time.sleep(8 * (попытка + 1))
    return {"ошибка": посл}

# ── летописи: попарное слепое сравнение двух кругов Сердца ──
ВОПРОС_ЛЕТОПИСИ = """Ты — редактор фэнтезийных хроник. Ниже две летописи одного и того же вымышленного мира (тёмное фэнтези: боги,
державы, города, подземелья, грани между мирами) за одинаковый срок. Мир один и тот же на старте, события выбирал
разный рассказчик. Имена новых сущностей — простые слова-заглушки (Ворон, Полынь…): разные имена — разные сущности;
качество имён не оценивай — оценивай ход событий.

Оцени каждую летопись по шкале 1–10:
- причинность: события вытекают одно из другого (бог пал — потому что угасла вера; город погиб — из-за войны, мора, тварей);
- интерес: хочется читать дальше, есть дуги и повороты, а не ровный поток мелочей;
- разнообразие: в мире происходит разное, а не одно и то же;
- правдоподобие: мир живёт по своим законам, нет нелепиц и суеты (вещь теряется и находится каждый год, город гибнет без причины).
И скажи, какая летопись лучше в целом (A или B), и одной фразой — почему.

Ответ — только JSON: {"A": {"причинность": n, "интерес": n, "разнообразие": n, "правдоподобие": n},
"B": {...}, "лучше": "A" или "B", "почему": "..."}

Летопись A:
<<A>>

Летопись B:
<<B>>"""

СЛОВА = ["Ворон", "Заря", "Полынь", "Янтарь", "Гроза", "Иней", "Пепел", "Сокол", "Терн", "Омут", "Кремень", "Ольха", "Багрец", "Сумрак",
         "Ковыль", "Рябина", "Морок", "Шиповник", "Курган", "Вереск", "Обсидиан", "Медь", "Сполох", "Туман", "Клевер", "Беркут", "Зимник",
         "Ясень", "Хмарь", "Лунь", "Солонец", "Жар", "Горицвет", "Дубрава", "Стрела", "Камыш", "Метель", "Перун", "Росток", "Сердолик"]
def заглушки():
    """различимые имена вместо «Безымянный вещь 1»: одно слово — одна сущность во всём мире (город и вещь не делят имя)"""
    счёт = [0]
    def f(вид, черты=None):
        i = счёт[0]; счёт[0] += 1; сл = СЛОВА[(i * 7) % len(СЛОВА)]
        return f"{сл}" + (f"-{i // len(СЛОВА) + 1}" if i >= len(СЛОВА) else "")
    return f

def летопись(T, сеть, зерно, лет, S, M):
    """летопись одного мира: жадно-случайный выбор сети (как в «Живом мире»), имена — различимые заглушки"""
    import torch, random as _r
    R = _r.Random(зерно); мир = M.Мир(T, зерно, имена=заглушки()); игрок = S.новый_игрок(R); torch.manual_seed(зерно)  # одно зерно — один прогон
    with torch.no_grad():
        for _ in range(лет):
            возм = мир.возможные(); маска = torch.full((S.E,), float("-inf"))
            for e in возм: маска[M.СОБЫТИЯ.index(e)] = 0
            x = torch.tensor(мир.признаки() + игрок + [S.напряжение(мир)], dtype=torch.float32)
            h, логиты, _ = сеть(x.unsqueeze(0)); p = torch.softmax(логиты[0] + маска, -1); ei = int(torch.multinomial(p, 1)); e = M.СОБЫТИЯ[ei]
            цели = возм[e] if len(возм[e]) <= 24 else R.sample(возм[e], 24)
            чц = torch.tensor([S.черты_цели(ц, мир, ei) for ц in цели], dtype=torch.float32)
            ц = цели[int(torch.multinomial(torch.softmax(сеть.оценка_целей(h, ei, чц), -1), 1))]; мир.шаг(e, ц)
    return "\n".join(f"Год {z['год']}. {z['текст']}" for z in мир.летопись)

def сравнить_летописи(папка, снА, снБ, миров=8, лет=80):
    import torch, mir as M, serdce as S
    T = json.load(open(os.path.join(папка, "world_tables.json"), encoding="utf-8"))
    сети = {}
    for имя, сн in (("A", снА), ("B", снБ)):
        c = torch.load(os.path.join(папка, сн) if not os.path.isabs(сн) else сн); сети[имя] = S.сеть_из(c, T).eval()
    R = random.Random(21); итог = {"A": {}, "B": {}}; побед = {"A": 0, "B": 0}; доводы = []
    for i in range(миров):
        зерно = 500 + i; тексты = {k: летопись(T, сети[k], зерно, лет, S, M) for k in сети}
        перев = R.random() < 0.5  # вслепую: кто окажется «A» в вопросе — случайно
        показ = {"A": тексты["B"], "B": тексты["A"]} if перев else тексты
        о = спросить(ВОПРОС_ЛЕТОПИСИ.replace("<<A>>", показ["A"]).replace("<<B>>", показ["B"]))
        if "ошибка" in о or "A" not in о: print("мир", зерно, "— без оценки:", о.get("ошибка", о)); continue
        назад = (lambda k: {"A": "B", "B": "A"}[k]) if перев else (lambda k: k)
        for k in ("A", "B"):
            for мера, v in о[k].items(): итог[назад(k)].setdefault(мера, []).append(float(v))
        if о.get("лучше") in ("A", "B"): побед[назад(о["лучше"])] += 1
        доводы.append(f"мир {зерно}: лучше {снА if назад(о.get('лучше', 'A')) == 'A' else снБ} — {о.get('почему', '')}")
        print(доводы[-1], flush=True)
    for k, сн in (("A", снА), ("B", снБ)):
        print(f"{сн}: " + ", ".join(f"{м} {sum(v)/len(v):.2f}" for м, v in итог[k].items()) + f"; лучше в {побед[k]} мирах")

# ── критика: слабые места летописей одного круга — сырьё для законов мира и награды следующего круга ──
ВОПРОС_КРИТИКА = """Ты — строгий редактор фэнтезийных хроник. Ниже летопись вымышленного мира (тёмное фэнтези: боги, державы,
города, подземелья, грани между мирами), события выбирал рассказчик-нейросеть. Имена — слова-заглушки, их не оценивай.
Найди до шести самых заметных слабостей хода событий: нелепицы, повторы, суета, события без причины, оборванные линии,
причина и следствие слишком далеко друг от друга, однообразие. Для каждой — короткое название рода слабости (одно-три
слова, обобщённо, например «повтор события», «гибель без причины»), годы-примеры и как это исправить законом мира.

Ответ — только JSON: {"слабости": [{"род": "...", "годы": [n, ...], "что": "...", "закон": "..."}, ...]}

Летопись:
<<Л>>"""

def критика(папка, сн, миров=8, лет=80):
    import torch, collections, mir as M, serdce as S
    T = json.load(open(os.path.join(папка, "world_tables.json"), encoding="utf-8"))
    сеть = S.сеть_из(torch.load(os.path.join(папка, сн)), T).eval(); роды = collections.Counter(); примеры = collections.defaultdict(list)
    for i in range(миров):
        о = спросить(ВОПРОС_КРИТИКА.replace("<<Л>>", летопись(T, сеть, 600 + i, лет, S, M)))
        for с in (о.get("слабости") or []) if isinstance(о, dict) else []:
            р = str(с.get("род", "")).strip().lower(); роды[р] += 1; примеры[р].append(f"мир {600 + i}: {с.get('что', '')} → {с.get('закон', '')}")
        print(f"мир {600 + i}: " + "; ".join(str(с.get("род")) for с in (о.get("слабости") or [])), flush=True)
    print("\nчаще всего:")
    for р, n in роды.most_common(12):
        print(f"- {р} — {n}"); [print("    " + x[:300]) for x in примеры[р][:3]]

# ── имена: оценки выдумкам Летописца ──
ВОПРОС_ИМЕНА = """Ты — редактор русскоязычной игры в жанре тёмного фэнтези. Нейросеть придумывает новые сущности мира: имя и
короткое описание. Оцени каждую запись по шкале 1–5:
5 — отличное имя этого вида, грамотный русский, звучит как имя из мира фэнтези, описание (если есть) связное;
4 — хорошее, мелкие шероховатости; 3 — сойдёт, но заметно странное; 2 — плохое: ошибки, корявый русский, не подходит
виду; 1 — бессмыслица, несуществующие слова, обрывки.
Вид — что это: бог, тварь, вещь (артефакт), ресурс, поселение (город), подземелье, земля (край), грань (мир за гранью),
персонаж, находка (предмет или место на дороге), миф и т. п.

Ответ — только JSON: {"оценки": [{"н": номер, "балл": n}, ...]} — по одной на каждую запись, в том же порядке.

Записи:
<<З>>"""

def оценить_имена(вход, выход, пачка=40):
    стр = [l.rstrip("\n").split("\t") for l in open(вход, encoding="utf-8") if l.strip()]
    готово = set()
    if os.path.exists(выход):
        for l in open(выход, encoding="utf-8"): готово.add(json.loads(l)["имя"])
    стр = [с for с in стр if len(с) >= 2 and с[1] not in готово]
    with open(выход, "a", encoding="utf-8") as f:
        for i in range(0, len(стр), пачка):
            ч = стр[i:i + пачка]
            з = "\n".join(f"{j+1}. вид: {с[0]}; имя: {с[1]}" + (f"; описание: {с[2][:120]}" if len(с) > 2 and с[2] else "") for j, с in enumerate(ч))
            о = спросить(ВОПРОС_ИМЕНА.replace("<<З>>", з))
            оц = {int(x["н"]): x["балл"] for x in (о.get("оценки") or []) if isinstance(x, dict) and "н" in x and "балл" in x} if isinstance(о, dict) else {}
            for j, с in enumerate(ч):
                if j + 1 in оц: f.write(json.dumps({"вид": с[0], "имя": с[1], "о": с[2] if len(с) > 2 else "", "балл": оц[j + 1]}, ensure_ascii=False) + "\n")
            f.flush(); print(f"оценено {min(i + пачка, len(стр))} из {len(стр)}", flush=True)

# ── образцы: Учитель пишет новые имена в духе игры — учебные примеры для Летописца (сам движок остаётся своим) ──
ВОПРОС_ОБРАЗЦЫ = """Ты — автор русскоязычной игры в жанре тёмного фэнтези «Грани миров». Вот настоящие примеры сущностей вида
«<<ВИД>>» из игры (имя — и, если есть, суть):
<<П>>

Придумай <<N>> НОВЫХ сущностей этого же вида в том же духе: грамотный русский, звучит как имя из этого мира, не
повторяй примеры и не делай вариаций одного слова. У каждой — имя (как в примерах: если там имена собственные —
имя собственное, если описательные — описательное) и короткая суть до 12 слов.

Ответ — только JSON: {"сущности": [{"имя": "...", "о": "..."}, ...]}"""

def образцы(корпус, выход, виды, n=40, примеров=20, зерно=17):
    import random as _r
    R = _r.Random(зерно); z = [json.loads(l) for l in open(корпус, encoding="utf-8")]
    готово = set()
    if os.path.exists(выход): готово = {json.loads(l)["вид"] for l in open(выход, encoding="utf-8")}
    with open(выход, "a", encoding="utf-8") as f:
        for в in виды:
            if в in готово: continue
            пр = [x for x in z if x["вид"] == в]; R.shuffle(пр)
            п = "\n".join(f"- {x['имя']}" + (f" — {x['о'][:90]}" if x.get("о") else "") for x in пр[:примеров])
            о = спросить(ВОПРОС_ОБРАЗЦЫ.replace("<<ВИД>>", в).replace("<<П>>", п).replace("<<N>>", str(n)), t=0.9)
            сп = (о.get("сущности") or []) if isinstance(о, dict) else []
            for x in сп:
                if isinstance(x, dict) and x.get("имя"): f.write(json.dumps({"вид": в, "имя": x["имя"].strip(), "о": (x.get("о") or "").strip()}, ensure_ascii=False) + "\n")
            f.flush(); print(в, len(сп), flush=True)

if __name__ == "__main__":
    if sys.argv[1] == "letopisi":
        сравнить_летописи(sys.argv[2], sys.argv[3], sys.argv[4], int(sys.argv[5]) if len(sys.argv) > 5 else 8, int(sys.argv[6]) if len(sys.argv) > 6 else 80)
    elif sys.argv[1] == "imena": оценить_имена(sys.argv[2], sys.argv[3])
    elif sys.argv[1] == "obrazcy": образцы(sys.argv[2], sys.argv[3], sys.argv[4].split(","), int(sys.argv[5]) if len(sys.argv) > 5 else 40, зерно=int(sys.argv[6]) if len(sys.argv) > 6 else 17)
    elif sys.argv[1] == "kritika": критика(sys.argv[2], sys.argv[3], int(sys.argv[4]) if len(sys.argv) > 4 else 8, int(sys.argv[5]) if len(sys.argv) > 5 else 80)
