def имя_цели(ц):
    if isinstance(ц, dict): return ц.get("имя") or ц.get("текст", "")[:30]
    if isinstance(ц, tuple): return "|".join(x["имя"] for x in ц)
    return ""

def связанные(мир, ц):
    """(11) имена, через которые цель связана с летописью: город — его держава, край, твари и грани края; край — его подземелья,
    твари и грань; тварь — её край; персонаж — его народ; артефакт — его владелец; грань — её край"""
    if isinstance(ц, tuple): return {x.get("имя") for x in ц if isinstance(x, dict)} - {None}
    if not isinstance(ц, dict): return set()
    и = {ц.get("имя") or ц.get("текст", "")[:30]}
    if мир is None: return и - {""}
    рег = ц.get("регион")
    if "держава" in ц: и.add(ц["держава"])                                   # город
    if ц.get("прежняя_держава"): и.add(ц["прежняя_держава"])                   # (17) восставший город помнит прежнюю державу
    if "подземелья" in ц:                                                     # край
        рег = ц.get("имя"); и |= {п["имя"] for п in ц.get("подземелья", [])}
        if ц.get("грань"): и.add(ц["грань"])
    if рег:
        и.add(рег); и |= {т["имя"] for т in мир.твари if т.get("регион") == рег}; и |= {г["имя"] for г in мир.грани if г.get("регион") == рег}
    if ц.get("народ"): и.add(ц["народ"])
    if ц.get("концы"): и |= set(ц["концы"])                                  # (17) торговый путь — его города
    if ц.get("основатель"): и.add(ц["основатель"])                             # (17) орден — его основатель
    if ц.get("у") and ц.get("у") not in ("утерян", "найден"): и.add(ц["у"])
    return и - {"", None}

def имена_записи(z):
    return set(z["причины"]) | {str(v) for v in z["след"].values()}

def причина_есть(мир, e, ц, прош=None):
    """связность: есть ли у события причина в недавней летописи (12 лет); «та же цель» — через связанные имена"""
    if прош is None: прош = мир.летопись[-12:]
    имя = имя_цели(ц); св = None; есть = 0.0
    for (пе, та_же) in ПРИЧИНЫ.get(e, []):
        for z in прош:
            if z["событие"] != пе: continue
            if not та_же: есть = 1.0; break
            if св is None: св = связанные(мир, ц)
            if (имя and (имя in z["причины"] or имя in "|".join(z["причины"]) or any(имя in str(v) for v in z["след"].values()))) or св & имена_записи(z): есть = 1.0; break
        if есть: break
    # причина бывает и в состоянии мира: бог, чья вера сама осела почти до нуля, падает не случайно
    if not есть and e == "бог_падает" and isinstance(ц, dict) and ц.get("вера", 1) < 0.12: есть = 0.7
    # (17) и город восстаёт не случайно, если его прежняя держава давно воюет или обессилела
    if not есть and e == "город_восстал" and isinstance(ц, dict) and мир is not None:
        стар = next((д for д in мир.державы if д["имя"] == ц.get("прежняя_держава")), None)
        if стар and ({w for w in стар["войны"] if w != ц.get("держава")} or стар["сила"] < 0.35): есть = 0.7
    return есть

ЧЕРТ = 10
def черты_цели(ц, мир=None, e=None):
    """10 чисел о цели — по ним сеть выбирает, с кем случится событие; (11) две последние — память летописи:
    упоминалась ли цель (или связанное с ней) за 12 лет и есть ли у этого события причина именно с этой целью"""
    if isinstance(ц, tuple):  # пара держав (война, мир), (17) пара городов (путь), герой и подземелье (поход)
        a, b = ц; сила = lambda x: float(x.get("сила", x.get("слава", x.get("население", 0))) or 0)
        ч = [сила(a), сила(b), len(a.get("войны", ())) / 5, len(a.get("города", [])) / 5, float(b.get("ярусов", 0) or 0) / 4, 0, 0, 1]
    elif not isinstance(ц, dict): ч = [0] * 7 + [1]
    else: ч = [float(ц.get("вера", 0) or 0), float(ц.get("сила", 0) or 0), float(ц.get("население", 0) or 0), float(ц.get("опасность", 0) or 0) / 5,
              len(ц.get("подземелья", []) or []) / 4, float(ц.get("числ", 0) or 0), float(ц.get("слава", 0) or 0), 1.0]
    if мир is None: return ч + [0.0, 0.0]
    прош = мир.летопись[-12:]; св = связанные(мир, ц)
    упом = 1.0 if св and any(св & имена_записи(z) for z in прош) else 0.0
    return ч + [упом, причина_есть(мир, M.СОБЫТИЯ[e], ц, прош) if e is not None and M.СОБЫТИЯ[e] in ПРИЧИНЫ else 0.0]

class Сердце(nn.Module):
    def __init__(s, вход, h=128):
        super().__init__(); s.тело = nn.Sequential(nn.Linear(вход, h), nn.Tanh(), nn.Linear(h, h), nn.Tanh())
        s.вид = nn.Linear(h, E); s.база = nn.Linear(h, 1)
        s.эмб = nn.Embedding(E, 16); s.цель = nn.Sequential(nn.Linear(h + 16 + ЧЕРТ, 64), nn.Tanh(), nn.Linear(64, 1))
    def forward(s, x): h = s.тело(x); return h, s.вид(h), s.база(h).squeeze(-1)
    def оценка_целей(s, h, e, черты): return s.цель(torch.cat([h.expand(len(черты), -1), s.эмб(torch.tensor([e] * len(черты))), черты], 1)).squeeze(-1)

def напряжение(мир):
    жд = мир.живые(мир.державы, "жива"); б = мир.живые(мир.боги)
    return min(1.0, 0.25 * sum(len(д["войны"]) for д in жд) / max(1, len(жд)) + 0.3 * sum(т["числ"] * т["сила"] for т in мир.живые(мир.твари)) / max(1, len(мир.живые(мир.твари)))
               + 0.25 * sum(1 for x in б if x["вера"] < 0.15) / max(1, len(б)) + 0.2 * sum(1 for г in мир.грани if г["открыта"]) / 4)

def награда(мир, e, ц, игрок, история):
    r = {}
    имя = имя_цели(ц); прош = мир.летопись[-13:-1]
    есть = причина_есть(мир, e, ц, прош)
    r["связность"] = есть if e in ПРИЧИНЫ else 0.3
    # (18б) лёгкая связность: причина таких событий обеспечена самим условием (битва и мир — только во время войны,
    # сопряжение и закрытие — только у открытой грани), и сеть 18-го круга копила их ради награды (8 войн за век)
    if e in ТРИВИАЛЬНЫЕ: r["связность"] = 0.2 + 0.5 * есть
    недавно = [z["событие"] for z in мир.летопись[-6:-1]]
    # то же событие с той же целью за 15 лет — повтор, а не история
    повтор = any(z["событие"] == e and имя and (имя in z["причины"] or имя == "|".join(z["причины"])) for z in мир.летопись[-16:-1])
    всего = sum(история.values()) or 1; доля = sum(v for k, v in история.items() if род(k) == род(e)) / всего
    r["новизна"] = -0.6 * недавно.count(e) - 0.25 * sum(1 for x in недавно if род(x) == род(e)) + 0.3 / (1 + история[e]) - 0.8 * повтор + 0.3 * (1 - доля) - 0.15
    # разрушительное без причины дорого; значимое — с выдержкой между крупными событиями
    # (13) штраф — разрушению без всякой причины; причина в состоянии мира (вера бога сама осела почти до нуля, 0,7) — не штрафуется:
    # прежде и она теряла 0,5, и сеть почти не роняла богов (1,7 падения за век), а без падений нет и наследников
    if e in РАЗРУШ and есть < 0.5: r["связность"] -= 0.5
    if e in ЗНАЧИМЫЕ: r["новизна"] += 0.25 if not any(z["событие"] in ЗНАЧИМЫЕ for z in мир.летопись[-4:-1]) else -0.2
    if история[e] == 1: r["новизна"] += 0.3  # первое за мир такое событие — разные пути, а не один
    # (14) гибель города — событие века: вторая за 30 лет (было — за 20) дорога; в 13-м круге городов гибло 4,1 за век при 2,5 у случайного выбора
    штраф_город = -0.6 if e == "город_гибнет" and sum(1 for z in мир.летопись[-31:-1] if z["событие"] == "город_гибнет") >= 1 else 0.0
    t = напряжение(мир); цель_t = 0.35 + 0.3 * math.sin(2 * math.pi * мир.год / 36)
    r["драматургия"] = 0.6 - 1.5 * abs(t - цель_t)
    б = len(мир.живые(мир.боги)); г = len(мир.живые(мир.города)); д = len(мир.живые(мир.державы, "жива"))
    r["равновесие"] = -1.0 * (б < 6) - 1.0 * (г < 6) - 1.0 * (д < 3) - 0.5 * (len(мир.живые(мир.твари)) > 45) - 0.5 * (б > 45) + штраф_город
    r["интерес"] = 1.2 * игрок[РОДЫ.index(род(e))]
    # состав: недопредставленный род (против смеси целевых долей и интересов игрока) поощряется
    смесь = {р: 0.6 * ЦЕЛЬ_ДОЛИ[р] + 0.4 * игрок[i] / 3 for i, р in enumerate(РОДЫ)}; сумма = sum(смесь.values())
    всего = sum(история.values()) or 1; было = sum(v for k, v in история.items() if род(k) == род(e)) - 1
    r["состав"] = 4.0 * (смесь[род(e)] / сумма - max(0, было) / max(1, всего - 1)) if всего > 1 else 0.0
    return r

ВЕС = {"связность": 1.0, "новизна": 0.7, "драматургия": 0.6, "равновесие": 1.0, "интерес": 0.8, "состав": 1.0}
# какой должна быть жизнь мира за век: доли родов событий (подмешиваются к интересам игрока)
ЦЕЛЬ_ДОЛИ = {"вера": 0.06, "бог": 0.09, "город": 0.08, "здание": 0.07, "подземелье": 0.08, "тварь": 0.10, "артефакт": 0.08, "ресурс": 0.06,
             "грань": 0.05, "сопряжение": 0.02, "ландшафт": 0.04, "земля": 0.02, "персонаж": 0.08, "война": 0.04, "мир": 0.03,
             "держава": 0.02, "объект": 0.03, "миф": 0.05,
             "мор": 0.02, "бедствие": 0.02, "путь": 0.04, "орден": 0.02, "поход": 0.03,
             "битва": 0.03}
ЦЕЛЬ_ДОЛИ["здание"] = 0.04  # (18) Учитель: «бытовые постройки рядом с падением богов — несоразмерность масштаба»
ЦЕЛЬ_ДОЛИ = {р: v / sum(ЦЕЛЬ_ДОЛИ.values()) for р, v in ЦЕЛЬ_ДОЛИ.items()}

# (SERD_KL) политика притягивается к замыслу: KL(π ‖ приор), приор — целевые доли родов, поровну между доступными
# событиями рода. Без этого сеть схлопывается на несколько лёгких цепочек (v1–v6: грань → сопряжение → закрылась)
KL_B = float(os.environ.get("SERD_KL", "0.2"))
def приор(возм):
    п = torch.zeros(E); по_роду = collections.Counter(род(e) for e in возм)
    for e in возм: п[M.СОБЫТИЯ.index(e)] = ЦЕЛЬ_ДОЛИ[род(e)] / по_роду[род(e)]
    return п / п.sum()

def новый_игрок(R):
    v = [R.random() ** 2 for _ in range(NR)]; s_ = sum(v); return [x / s_ * 3 for x in v]

def эпизод(T, сеть, R, шагов=120, жадно=False, случайно=False, зерно=None):
    мир = M.Мир(T, зерно if зерно is not None else R.randrange(10 ** 6)); игрок = новый_игрок(R); история = collections.Counter()
    лог_p, базы, наградыt, энтр, части, кл = [], [], [], [], collections.defaultdict(float), []
    for _ in range(шагов):
        возм = мир.возможные(); маска = torch.full((E,), float("-inf"))
        for e in возм: маска[M.СОБЫТИЯ.index(e)] = 0
        x = torch.tensor(мир.признаки() + игрок + [напряжение(мир)], dtype=torch.float32)
        if случайно:
            e = R.choice(list(возм)); ц = R.choice(возм[e]); мир.шаг(e, ц)
        else:
            h, логиты, база = сеть(x.unsqueeze(0)); p = F.softmax(логиты[0] + маска, -1)
            ei = int(p.argmax()) if жадно else int(torch.multinomial(p, 1)); e = M.СОБЫТИЯ[ei]
            цели = возм[e]; цели = цели if len(цели) <= 24 else R.sample(цели, 24)
            чц = torch.tensor([черты_цели(ц, мир, ei) for ц in цели], dtype=torch.float32)
            pц = F.softmax(сеть.оценка_целей(h, ei, чц), -1); ci = int(pц.argmax()) if жадно else int(torch.multinomial(pц, 1))
            ц = цели[ci]; мир.шаг(e, ц)
            лог_p.append(torch.log(p[ei] + 1e-9) + torch.log(pц[ci] + 1e-9)); базы.append(база[0])
            энтр.append(-(p[p > 0] * torch.log(p[p > 0])).sum())
            if KL_B: пр = приор(возм); д = p > 0; кл.append((p[д] * (torch.log(p[д]) - torch.log(пр[д] + 1e-9))).sum())
        история[e] += 1
        r = награда(мир, e, ц, игрок, история); rr = sum(ВЕС[k] * v for k, v in r.items())
        мир.летопись[-1]["связно"] = r["связность"] >= 1.0
        for k, v in r.items(): части[k] += v / шагов
        наградыt.append(rr)
    эпизод.кл = кл
    return мир, лог_p, базы, наградыt, энтр, части, история

def загрузить_веса(сеть, c):
    """веса из снимка; снимок до 11-го круга (8 черт цели) расширяется нулями под новые черты — поведение то же,
    пока сеть не научится ими пользоваться. (17) Снимок с другим набором событий и признаков переносится по именам:
    вес входа — тому же признаку, строка выхода и вектор события — тому же событию; новым входам — нули, новым
    событиям — средний сдвиг прежних (не задавлены с первого шага). Возвращает True, если состояние оптимизатора подходит."""
    св = dict(c["сеть"]); w = св["цель.0.weight"]; нужно = сеть.цель[0].weight.shape[1]; годен = True
    if w.shape[1] < нужно:
        св["цель.0.weight"] = torch.cat([w, torch.zeros(w.shape[0], нужно - w.shape[1])], 1); годен = False
    им_было = c.get("имена_входа") or ИМЕНА_16; соб_было = c.get("события") or СОБЫТИЯ_16; им = имена_входа()
    if им_было != им or list(соб_было) != list(M.СОБЫТИЯ):
        new = сеть.state_dict(); W = св["тело.0.weight"]; Wn = torch.zeros_like(new["тело.0.weight"])
        for j, n in enumerate(им):
            if n in им_было: Wn[:, j] = W[:, им_было.index(n)]
        св["тело.0.weight"] = Wn
        V, b, Э = св["вид.weight"], св["вид.bias"], св["эмб.weight"]
        Vn = torch.zeros_like(new["вид.weight"]); bn = torch.full_like(new["вид.bias"], float(b.mean())); Эn = new["эмб.weight"].clone() * 0.1
        for i, e in enumerate(M.СОБЫТИЯ):
            if e in соб_было: k = list(соб_было).index(e); Vn[i] = V[k]; bn[i] = b[k]; Эn[i] = Э[k]
        св["вид.weight"], св["вид.bias"], св["эмб.weight"] = Vn, bn, Эn; годен = False
    сеть.load_state_dict(св); return годен

def вход_мира(T): return len(M.Мир(T, 0).признаки()) + NR + 1

def сеть_из(c, T):
    """Сердце под нынешний мир из снимка любого круга"""
    сеть = Сердце(вход_мира(T)); загрузить_веса(сеть, c); return сеть

def учить(папка, эпизодов):
    torch.set_num_threads(1); torch.manual_seed(3); R = random.Random(3)
    T = json.load(open(os.path.join(папка, "world_tables.json"), encoding="utf-8"))
    вход = вход_мира(T); сеть = Сердце(вход); пут = os.path.join(папка, "serdce.pt"); эп0 = 0
    опт = torch.optim.Adam(сеть.parameters(), lr=1e-3)
    if os.path.exists(пут):
        c = torch.load(пут); эп0 = c["эп"]
        if загрузить_веса(сеть, c): опт.load_state_dict(c["опт"])
        else: print(f"снимок с {эп0} эпизодов перенесён под нынешний мир ({E} событий, {вход} входов); оптимизатор — заново", flush=True)
    γ = 0.95; t0 = time.time(); ср = None
    for эп in range(эп0, эпизодов):
        _, лог_p, базы, нагр, энтр, части, _ = эпизод(T, сеть, R)
        G, отд = 0.0, []
        for rr in reversed(нагр): G = rr + γ * G; отд.append(G)
        отд = torch.tensor(list(reversed(отд))); б = torch.stack(базы); adv = отд - б.detach(); adv = (adv - adv.mean()) / (adv.std() + 1e-6)
        потеря = -(torch.stack(лог_p) * adv).sum() / len(нагр) + 0.5 * F.mse_loss(б, отд) / 10 - 0.01 * torch.stack(энтр).mean()
        if KL_B and эпизод.кл: потеря = потеря + KL_B * torch.stack(эпизод.кл).mean()
        опт.zero_grad(); потеря.backward(); torch.nn.utils.clip_grad_norm_(сеть.parameters(), 1.0); опт.step()
        сумма = sum(нагр) / len(нагр); ср = сумма if ср is None else 0.97 * ср + 0.03 * сумма
        if (эп + 1) % 20 == 0:
            print(f"эпизод {эп+1}: награда {ср:.3f} | " + ", ".join(f"{k} {v:.2f}" for k, v in части.items()) + f" | {time.time()-t0:.0f} с", flush=True)
        if (эп + 1) % 100 == 0 or эп + 1 == эпизодов:
            torch.save({"сеть": сеть.state_dict(), "опт": опт.state_dict(), "эп": эп + 1, "вход": вход, "имена_входа": имена_входа(), "события": list(M.СОБЫТИЯ)}, пут)

@torch.no_grad()
def сравнить(папка, n=30):
    T = json.load(open(os.path.join(папка, "world_tables.json"), encoding="utf-8")); c = torch.load(os.path.join(папка, os.environ.get("SERD_PT", "serdce.pt")))
    сеть = сеть_из(c, T); итоги = {}
    for вид, кв in [("случайно", dict(случайно=True)), ("сеть", dict())]:
        R = random.Random(11); сумм = collections.defaultdict(float); раз = []
        for i in range(n):
            мир, _, _, нагр, _, части, ист = эпизод(T, сеть, R, зерно=1000 + i, **кв)
            for k, v in части.items(): сумм[k] += v / n
            сумм["награда"] += sum(нагр) / len(нагр) / n
            p = [v / sum(ист.values()) for v in ист.values()]; раз.append(-sum(x * math.log(x) for x in p if x > 0))
            сумм["живых богов"] += len(мир.живые(мир.боги)) / n; сумм["новых богов"] += sum(1 for b in мир.боги if b.get("род") == "новый") / n
            for e, к in [("бог_дух_места", "дух места: с причиной"), ("город_гибнет", "гибель города: с причиной")]:
                всего_e = [z for z in мир.летопись if z["событие"] == e]
                сумм[к] += (sum(1 for z in всего_e if z.get("связно")) / len(всего_e) if всего_e else 0) / n
            for e, к in [("бог_падает", "падений"), ("бог_наследник", "наследников"), ("бог_апофеоз", "апофеозов"), ("бог_дух_места", "духов мест"),
                         ("бог_из_грани", "из граней"), ("город_гибнет", "гибели городов"), ("грань_открылась", "граней")]: сумм[к] += ист[e] / n
            # (15-й круг) потери вещей и сколько лет живёт грань до закрытия
            сумм["потерь вещей"] += ист["артефакт_утерян"] / n
            # (17-й круг) новые силы мира: сколько за век и с причиной ли
            for e, к in [("мор", "моров"), ("бедствие", "бедствий"), ("путь_проложен", "путей"), ("путь_прерван", "путей прервано"),
                         ("орден_основан", "орденов"), ("город_восстал", "восстаний"), ("поход_в_глубины", "походов"),
                         ("битва", "битв"), ("война", "войн"), ("артефакт_найден", "вещей найдено"), ("миф_родился", "мифов")]: сумм[к] += ист[e] / n
            for e, к in [("мор", "мор: с причиной"), ("город_восстал", "восстание: с причиной"), ("поход_в_глубины", "поход: с причиной")]:
                всего_e = [z for z in мир.летопись if z["событие"] == e]
                сумм[к] += (sum(1 for z in всего_e if z.get("связно")) / len(всего_e) if всего_e else 0) / n
            откр = {z["след"].get("грань"): z["год"] for z in мир.летопись if z["событие"] == "грань_открылась"}
            жизнь = [z["год"] - откр[z["причины"][0]] for z in мир.летопись if z["событие"] == "грань_закрылась" and z["причины"] and z["причины"][0] in откр]
            сумм["жизнь грани, лет"] += (sum(жизнь) / len(жизнь) if жизнь else 0) / n
            # отклонение состава от замысла: сумма |доля рода − целевая доля|
            вс = sum(ист.values()); сумм["откл. состава"] += sum(abs(sum(v for k, v in ист.items() if род(k) == р) / вс - ЦЕЛЬ_ДОЛИ[р]) for р in РОДЫ) / n
        сумм["разнообразие"] = sum(раз) / n; итоги[вид] = dict(сумм)
    for вид, s in итоги.items(): print(вид + ": " + ", ".join(f"{k} {v:.2f}" for k, v in s.items()))
    R = random.Random(5); мир, *_ = эпизод(T, сеть, R, шагов=60, зерно=77)
    for z in мир.летопись: print(f"Год {z['год']}. {z['текст']}")

if __name__ == "__main__":
    if sys.argv[1] == "train": учить(sys.argv[2], int(sys.argv[3]) if len(sys.argv) > 3 else 1500)
    else: сравнить(sys.argv[2])
