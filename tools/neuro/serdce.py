"""serdce.py — Сердце мира: сеть, которая решает, что случится в мире дальше (в игру не входит).

Вход: признаки мира (mir.Мир.признаки) и предпочтения игрока (чем он больше занят: богами, городами, подземельями,
тварями, вещами, гранями…). Выход: вид события (из возможных сейчас) и его цель (оценка каждой возможной цели по
её чертам). Учится с подкреплением (REINFORCE с базой и бонусом за неопределённость) в симуляторе mir.py.

Награда за ход:
  связность   — у события есть причина в недавней летописи (бог падает после угасания веры; наследник — после
                падения; город гибнет после войны или натиска тварей; сопряжение — после открытия грани…);
  новизна     — не повторять одно и то же подряд, давать редким событиям случаться;
  драматургия — напряжение мира (войны, натиск тварей, слабые боги, открытые грани) идёт дугами: растёт и
                разрешается, а не стоит на месте;
  равновесие  — мир не вымирает: богов, городов и держав не меньше порога, твари не захватывают всё;
  интерес     — события того рода, который игрок любит (его предпочтения — на входе сети).

  python3 serdce.py train <папка данных> [эпизодов]
  python3 serdce.py eval  <папка данных>      — сравнение со случайным выбором и летопись обученного мира
"""
