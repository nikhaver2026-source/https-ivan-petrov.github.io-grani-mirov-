def iid(name): return "kv_" + str(int(hashlib.md5(name.encode()).hexdigest(), 16) % 100000)


def build(canon, stats, schools):
    ош = []; out = []
    вещи = [z for z in canon if z["вид"] == "вещь"]
    for z in вещи:
        if z["имя"] not in P: ош.append(f"вещь канона «{z['имя']}» без разметки")
    for n in P:
        if not any(z["имя"] == n for z in вещи): ош.append(f"разметка вещи «{n}» без вещи в каноне")
    for z in вещи:
        if z["имя"] not in P: continue
        дом, ст, особ = P[z["имя"]]
        р = РАНГ.get(z["черты"].get("ранг", ""), None)
        if р is None: ош.append(f"{z['имя']}: ранг {z['черты'].get('ранг')}"); continue
        база = {}
        for k, доля in ст.items():
            if k not in stats: ош.append(f"{z['имя']}: нет характеристики {k}"); continue
            v = stats[k] * МОЩЬ[р] * доля
            база[k] = round(v, 3) if k in ДОЛИ else (int(round(v)) or (1 if доля > 0 else -1))
        дела = []
        for o in особ:
            k = o.split(":")[0]
            if k not in ДЕЛО: ош.append(f"{z['имя']}: особое {o}"); continue
            if k == "школа":
                sid = o.split(":")[1]
                if sid not in schools: ош.append(f"{z['имя']}: школы {sid} нет")
                дела.append(f"чары школы «{schools.get(sid, sid)}» сильнее на {int(float(o.split(':')[2]) * 100)} %")
            else: дела.append(ДЕЛО[k])
        out.append(dict(id=iid(z["имя"]), имя=z["имя"], дом=дом, ранг=р, база=база, особ=особ, дело="; ".join(дела),
                        о=z["о"].rstrip("."), облик=z["черты"].get("облик", ""), части=z["черты"].get("части", ""), звукО=z.get("звук", ""), пакет=z["пакет"]))
    ids = [x["id"] for x in out]
    if len(set(ids)) != len(ids): ош.append("повтор id вещи")
    return out, ош
