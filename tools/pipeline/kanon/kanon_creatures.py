def biomes_of(z):
    t = (z.get("черты", {}).get("водится", "") + " " + z.get("о", "")).lower()
    out = [b for rx, b in BIOME if re.search(rx, t)]
    return list(dict.fromkeys(out)) or ["plains"]

def family_of(z):
    t = (z["имя"] + " " + z.get("о", "")).lower()
    for rx, f in FAMILY:
        if re.search(rx, t): return f
    return "beast"

def skills_of(z):
    t = (z.get("механика", "") + " " + z.get("о", "")).lower()
    out = [s for rx, s in УМЕНИЯ if re.search(rx, t)]
    return list(dict.fromkeys(out))[:3]

def levels_of(z, h):
    t = (z.get("черты", {}).get("нрав", "") + " " + z.get("о", "") + " " + z.get("механика", "")).lower()
    if re.search(r"босс|владык|привратник|держит прорыв|огромн|исполин|размером с телегу|шатун|голиаф", t): lo = 7 + h % 3
    elif re.search(r"трусл|пугл|мелк|маленьк|до 5-го|слабых", t): lo = 1
    elif re.search(r"стай|хищн|яростн|засадн", t): lo = 2 + h % 3
    else: lo = 2 + h % 4
    return lo, lo + 6 + h % 3

ПРАВКИ = {
 # имя: {поле: значение} — где правила ошиблись
}
ТРОФЕЙ = {"bird": "перо", "crawler": "хитин", "beast": "клык", "giant": "жила", "construct": "сердцевина", "spirit": "эссенция",
          "undead": "прах", "fiend": "рог", "dragon": "чешуя", "deep": "слизь", "humanoid": "оберег", "bone": "кость"}

def build(canon, gent):
    out = []
    for z in [z for z in canon if z["вид"] == "тварь"]:
        h = int(hashlib.md5(z["имя"].encode()).hexdigest()[:6], 16)
        fam = family_of(z); lo, hi = levels_of(z, h)
        rec = dict(id=f"kn_{z['пакет']}_{h % 100000:05d}", n=z["имя"], biomes=biomes_of(z), min=lo, max=hi, род=fam, умения=skills_of(z),
                   о=z["о"], механика=z.get("механика", ""), звукО=z.get("звук", ""), нрав=z.get("черты", {}).get("нрав", ""),
                   охотится=z.get("черты", {}).get("охотится", ""), пакет=z["пакет"])
        rec["snd"], rec["fx"] = ГОЛОС.get(fam, ("mgrowl", "growl"))
        if fam in ("spirit", "undead"): rec["нежить"] = True
        if fam == "bird" or re.search(r"летает|парит|летит", z.get("о", "").lower()): rec["fly"] = 2 if fam == "bird" else 1
        if РОЕТ.search((z.get("механика", "") + " " + z.get("о", "")).lower()): rec["роет"] = True
        rec["трофей"] = f"{ТРОФЕЙ.get(fam, 'клык')} {gent(z['имя'])}"
        rec.update(ПРАВКИ.get(z["имя"], {}))
        out.append(rec)
    return out

