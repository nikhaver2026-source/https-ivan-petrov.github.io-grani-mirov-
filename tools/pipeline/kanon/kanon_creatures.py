def build_manual(canon):
    out = []
    names = {z["имя"] for z in canon if z["вид"] == "тварь"}
    miss = sorted(names - set(Р)); extra = sorted(set(Р) - names)
    assert not miss and not extra, (miss, extra)
    for z in [z for z in canon if z["вид"] == "тварь"]:
        fam, biomes, lo, hi, ум, доп, трофей = Р[z["имя"]]
        h = int(hashlib.md5(z["имя"].encode()).hexdigest()[:6], 16)
        rec = dict(id=f"kn_{z['пакет']}_{h % 100000:05d}", n=z["имя"], biomes=biomes, min=lo, max=hi, род=fam, умения=ум,
                   о=z["о"], механика=z.get("механика", ""), звукО=z.get("звук", ""), нрав=z.get("черты", {}).get("нрав", ""),
                   охотится=z.get("черты", {}).get("охотится", ""), пакет=z["пакет"], трофей=трофей)
        rec["snd"], rec["fx"] = ГОЛОС.get(fam, ("mgrowl", "growl"))
        if fam in ("spirit", "undead"): rec["нежить"] = True
        rec.update(доп)
        out.append(rec)
    return out
