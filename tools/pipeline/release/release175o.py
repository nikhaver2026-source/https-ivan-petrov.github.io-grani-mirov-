"""release175o.py — установка отдельного «голосового пакета» убрана: пакет внутри игры (26 октября).

Просьба игрока: «Не забывай проверять на старые обработчики и дублирующие модули… Если старые обработчики или
дублирующие модули конфликтуют или вообще не нужны, удаляй их». Правило сборок (CLAUDE.md): всё, что нужно игре, лежит
в самой игре — никаких голосовых пакетов отдельными файлами и докачки. С 17.0 записи «голосового пакета» Gemini лежат в
полной сборке (sounds/gvoice_pack), а в настройках оставались кнопка «Голосовой пакет» / «Установить голосовой пакет»,
команда установки из скачанного GraniMirov-voicepack.zip, отклик приложения об установке и абзац руководства о том, как
пакет скачать. Всё это убрано; сами записи пакета, как и прежде, грузятся из папки игры (gvPackLoad).
Повторный запуск ничего не меняет."""
import re
B = "/root/S/hron/index_before_mater.html"
s = open(B, encoding="utf-8").read()
n0 = len(s)


def cut(a, b, mark):
    """вырезать от a до b (b — не входит); если метки a уже нет — ничего не делать"""
    global s
    if mark not in s:
        return
    i = s.index(a)
    assert s.count(a) == 1, ("a", s.count(a), a[:60])
    j = s.index(b, i)
    s = s[:i] + s[j:]


def sub(a, b, n=1):
    global s
    if a not in s:
        return
    assert s.count(a) == n, (s.count(a), a[:80])
    s = s.replace(a, b)


# 1. Настройки «Синтезатор»: строка о пакете и кнопка
cut(' <p class="hint" id="gvPackHint"', ' <label class="opt"><input type="checkbox" id="setEngDevice">', 'id="gvPackHint"')
# 2. Команда «Голосовой пакет»
cut(' /* Голосовой пакет Gemini: в приложениях — поставить из скачанного файла,', ' voicelist(){', ' gvpack(){')
# 3. Строка о пакете, проверка «встроен ли» и отклик приложения об установке
cut('/* Строка о голосовом пакете в разделе «Синтезатор». */', 'function isDesktopApp(){', 'function gvPackUi(){')
# 4. Опись пакета больше не обновляет строку в настройках
sub('\n   safeFn(()=>{if(typeof gvPackUi==="function")gvPackUi();});', '')
sub(';safeFn(()=>{if(typeof gvPackUi==="function")gvPackUi();});', ';')
sub('safeFn(()=>{Speech.gvPackLoad(Speech.GVOICE);gvPackUi();});', 'safeFn(()=>Speech.gvPackLoad(Speech.GVOICE));')
# 5. Пояснение к описям и руководство: пакет — в самой игре
sub('''сборки, — отдельным файлом. В веб-версии пакет лежит на сайте и
    подключается сам; в приложениях для Windows и Android его ставят один раз
    (настройки, «Синтезатор», «Голосовой пакет»), и приложение отдаёт его по
    тому же адресу sounds/gvoice_pack/. Нет пакета — звучит то, что вшито. */''', '''сборки, — отдельной описью. (26 октября) Пакет лежит в самой игре (sounds/gvoice_pack) — в полной
    сборке для Windows и Android и на сайте одинаково; ставить и скачивать его не нужно. */''')
sub('''ГОЛОСОВОЙ ПАКЕТ: в полной сборке (Windows и Android) он уже внутри — ставить ничего не нужно, кнопки установки нет. Для обычной сборки всё, что голос Gemini прочёл сверх вшитого в игру, выходит отдельным файлом GraniMirov-voicepack.zip (выпуск «voicepack-latest»). В приложении для Windows достаточно скачать его в «Загрузки» — приложение найдёт его само; или Настройки → Синтезатор → «Установить голосовой пакет» и выбрать файл. На Android — та же кнопка. Распаковывать не нужно; в веб-версии пакет подключается сам.''',
    '''ЗАПИСИ ГОЛОСА: все записи голоса Gemini — внутри игры, в любой сборке; скачивать и ставить ничего не нужно.''')

for left in ('gvPackUi', 'GraniVoicePackDone', 'installVoicePack', 'btnGvPack', 'gvPackBuiltin', 'GraniMirov-voicepack'):
    assert left not in s, left
open(B, "w", encoding="utf-8").write(s)
print("основа: голосовой пакет —", "без изменений" if len(s) == n0 else f"установка убрана ({len(s)-n0:+d} знаков)")
