# Руководство (15.0): голос героя — до пяти реплик на ход разговора; голос игры по полу героя;
# героине жители говорят в женском обращении своими голосами. Ставится, только когда записи
# встроены (hron/voice150_data.json есть) — иначе руководство обещало бы то, чего нет.
import os,sys,json
H=os.path.dirname(os.path.abspath(__file__))
if not os.path.exists(os.path.join(H,'voice150_data.json')):print('voice150: данных нет, руководство не меняется');sys.exit(0)
sys.path.insert(0,os.path.join(os.path.dirname(H),'guide3'))
from guidelib import Guide
R='/home/user/https-ivan-petrov.github.io-grani-mirov-/'
d=json.load(open(os.path.join(H,'voice150_data.json'),encoding='utf-8'))
g=Guide()
if d.get('hero_vars'):
    g.sub(50,'ГОЛОС ГЕРОЯ. Ходы разговора озвучены отдельно.','у каждого хода своя реплика, и она идёт первой, до ответа собеседника.',
          'у каждого хода — до пяти реплик, записанных голосом, который выбран в «Настройках персонажа»; герой не повторяет одну и ту же подряд, а его слово идёт первым, до ответа собеседника.')
add=' Голос игры по умолчанию следует полу героя: героиня слышит женский голос, герой — мужской; голос, выбранный в настройках, пол героя больше не меняет.'
if d.get('fem',{}).get('lines'):
    add+=' Героине житель, торговец, стражник, обозник и тварь говорят в женском обращении своими голосами: «путница», «ты пришла»; мужского обращения героиня не слышит — если записи с женским обращением нет, строку читает голос игры.'
p=g.para(106,'ПОЛ ГОЛОСА.');p['text']=p['text'].rstrip()+add;p['changed']=True
src=g.src[:g.a]+g.render()+g.src[g.e:]
open(R+'index.html','w',encoding='utf-8').write(src)
print('voice150: руководство обновлено')
