function envState(rm, env, sp, fx) {
  var out = { fog: 0, block: "", note: "" }, T = ENV_T[fx === "mushrooms" ? "fungus" : fx === "moss" || fx === "roots" || fx === "palm" ? "other" : "leaf"];
  if (!rm) return out;
  if (rm.rad >= 1 && sp.cls !== "relic") out.block = T.rad;
  else if (rm.gas >= 1) out.block = T.gas;
  else if (env.temp != null && env.temp < 3) out.block = T.cold;
  else if (env.temp != null && env.temp > 38 && sp.cls !== "relic") out.block = T.hot;
  if (rm.fog > 0) { out.fog = rm.fog; out.note = T.fog; }
  return out;
}
/* ════════ ВЕЩЬ ОБСТАНОВКИ — ПО ВИДУ ════════
   fixtures.js (VAR) спрашивает здесь: вид, описание, пункты. env — что знает fixtures.js:
   температура помещения (roomTemp), пчёлы и дроны рядом, урожайное ли помещение, ростки. */
function variant(fx, o, def, t, rm, env) {
  env.era = env.era || eraOfL(env.L);
  env.ctx = ctxOf(rm, env.L, env.era, env);
  var sp = speciesOf(fx, o, t, rm, env);
  if (!sp) return null;
  var E = envState(rm, env, sp, fx), water = (def.a || []).filter(function (a) { return a[0] === "listen" && /Полить/.test(a[1]); })[0] || null;
  var d = sp.d || def.d, acts = [], harvest = (def.a || []).filter(function (a) { return a[0] === "harvest"; })[0] || null;
  if (sp.dead) d = sp.d;
  if (E.note && !sp.dead) d += " " + E.note;
  if (E.block && !sp.dead && (sp.fruit || harvest) && sp.spec !== "decor") d += " " + E.block;
  /* плоды */
  var fruit = sp.fruit || (fx !== "plants" && harvest && harvest[2] && harvest[2].item) || null;
  if (fruit && !E.block && !sp.dead && sp.spec !== "decor" && sp.spec !== "aroma") {
    var every = sp.every != null ? sp.every : (harvest && harvest[2] && harvest[2].every) || 300;
    if (E.fog && every > 0) every = Math.round(every * (1 - 0.15 * Math.min(3, E.fog)));
    var item = E.fog && LAB.ITEMS[mutId(fruit)] ? mutId(fruit) : fruit;
    var p = { item: item, every: every, plant: sp.id, oko: (env.ctx === "okocrop" && sp.oko) ? sp.oko : 0, bees: !!env.bees };
    var hp0 = harvest && harvest[2] || {};
    if (sp.max) { p.max = sp.max; p.none = sp.none; }
    else if (hp0.max) { p.max = hp0.max; p.none = hp0.none; }
    if (hp0.risk) p.risk = hp0.risk;
    if (hp0.extra) { p.extra = hp0.extra; p.extraL = hp0.extraL; }
    acts.push(["harvest", (sp.cut || (harvest && harvest[1]) || "Сорвать плод"), p]);
  }
  /* прежние пункты вещи (понюхать грибы, порыться в кадке, полежать на мху…) — кроме сбора и полива */
  (def.a || []).forEach(function (a) { if (a[0] !== "harvest" && a !== water) acts.push(a); });
  if (fx === "plants" || fx === "appletree" || fx === "berrybush") acts.push(["pwater", sp.dead ? "Полить засохший фикус" : "Полить растения", { plant: sp.id, drip: !!sp.drip || env.ctx === "okocrop" || env.ctx === "okooffice", t: water && water[2] && water[2].t }]);
  if (sp.label && env.ctx !== "wild") acts.push(["plabel", /^Ярлык ОКО|^Ярлык Садовника/.test(sp.label) ? "Прочитать ярлык" : /^Записка|^Карточка|^Бумажка|^Мелом|^Табличка/.test(sp.label) ? "Прочитать надпись у растения" : "Прочитать бирку", { plant: sp.id }]);
  var keepName = fx === "palm" || fx === "moss" || fx === "roots" || fx === "mushrooms";
  var v = { n: keepName ? def.n : sp.n, d: keepName ? (E.note ? def.d + " " + E.note : def.d) : d, a: acts, base: def, plant: sp.id, fog: E.fog, block: E.block, wild: env.ctx === "wild" };
  return v;
}

/* ════════ СОСТОЯНИЕ ГЕРОЯ: что встречено, курсы, прибавки ════════ */
function st() {
  var g = G();
  if (!g.plants) g.plants = {};
  var P = g.plants;
  if (!P.seen) P.seen = {};
  if (!P.fx) P.fx = {};
  if (!P.course) P.course = {};
  if (!P.ate) P.ate = {};
  return P;
}
var STAT_N = { str: "сила", agi: "ловкость", mind: "интеллект", cha: "харизма" };
var STAT_A = { str: "силу", agi: "ловкость", mind: "интеллект", cha: "харизму" };
var LINE_N = { str: "«Атлант» (Х-17)", agi: "лимонника «Глубина»", mind: "нервного корня (Н-4)", cha: "лунника Лидии" };
var FX_MAX = 360, COURSE_GAP = 360, COURSE_N = 3;
/* Характеристика героя с прибавкой от плода (если действует); без G — по текущей игре */
function heroStat(k, g0) {
  var g = g0 || (LAB.game && LAB.game.G);
  if (!g) return 10;
  var base = g[k] == null ? 10 : g[k], P = g.plants, f = P && P.fx && P.fx[k];
  return f && f.until > nowOf(g) ? Math.min(50, base + f.v) : base;
}
function boostOf(k) { var P = st(), f = P.fx[k]; return f && f.until > nowMin() ? f : null; }
function applyBoost(d, msg) {
  var P = st(), k = d.pfx.k, now = nowMin(), cur = boostOf(k), until, tail;
  if (cur && cur.v > d.pfx.v) {
    until = Math.min(now + FX_MAX, cur.until + d.pfx.min);
    tail = until > cur.until ? " Плод лишь продлил её — ещё на " + minW(until - now) + "." : "";
    cur.until = until;
    msg.push(cap(STAT_N[k]) + " и так поднята сильнее, плюс " + cur.v + "." + tail);
    return;
  }
  until = Math.min(now + FX_MAX, cur ? cur.until + d.pfx.min : now + d.pfx.min);
  P.fx[k] = { v: d.pfx.v, until: until, crash: d.crash || (cur && cur.crash) || null, src: d.base ? (LAB.ITEMS[d.base] || d).n : d.n };
  msg.push(cap(STAT_N[k]) + " плюс " + d.pfx.v + (cur ? ": действие продлено — ещё " + minW(until - now) : " на " + minW(until - now)) + ", теперь " + heroStat(k) + "." + (until - now >= FX_MAX && cur ? " Дольше шести часов действие плодов не тянется." : ""));
}
function courseDose(d, msg) {
  var P = st(), k = d.course, c = P.course[k] || (P.course[k] = { n: 0, last: null, done: 0 }), now = nowMin(), g = G();
  if (c.done) return;
  if (c.last != null && now - c.last < COURSE_GAP) { msg.push("Курс линии " + LINE_N[k] + ": рано — с прошлого приёма прошло меньше шести часов, этот не засчитан. Следующий засчитается через " + minW(COURSE_GAP - (now - c.last)) + "."); return; }
  c.n++; c.last = now;
  if (c.n < COURSE_N) { msg.push("Курс линии " + LINE_N[k] + ": приём " + c.n + " из " + COURSE_N + ". Следующий засчитается не раньше чем через шесть часов."); return; }
  c.done = 1;
  var base = g[k] == null ? 10 : g[k];
  if (base >= 40) { msg.push("Курс линии " + LINE_N[k] + " пройден, но " + STAT_N[k] + " и так на пределе — прибавки не будет."); return; }
  g[k] = base + 1;
  msg.push("Курс линии " + LINE_N[k] + " пройден: " + STAT_N[k] + " навсегда плюс один, теперь " + g[k] + " без плодов.");
  if (LAB.ach) LAB.ach.ev("plant_course", 1);
}
/* Съели плод (game.useItem, после bodyApply): прибавка, курс, мутаген, Плод первого дерева */
function eat(id, d, msg) {
  var P = st(), base = d.base || id;
  P.ate[base] = (P.ate[base] || 0) + 1;
  if (d.pfx) applyBoost(d, msg);
  if (d.mutAdd && LAB.chem && LAB.chem.addMut) {
    var x = d.mutAdd * (LAB.chem.rank && LAB.chem.rank("bio") >= 2 ? 0.5 : 1);
    LAB.chem.addMut(x, "плод");
    msg.push("Мутаген из тумана: мутация плюс " + (Math.round(x * 10) / 10) + ".");
  }
  if (d.cutMut && LAB.chem && LAB.chem.cutMut) {
    var m0 = LAB.chem.mut ? LAB.chem.mut() : 0;
    LAB.chem.cutMut(d.cutMut);
    msg.push(m0 > 0 ? "Мутация отступает: " + Math.round(LAB.chem.mut()) + " из 100." : "Мутации не было — тело просто стало легче.");
  }
  if (d.course) courseDose(d, msg);
  else if (d.mutagen && LAB.ITEMS[base] && LAB.ITEMS[base].course && !(P.course[LAB.ITEMS[base].course] || {}).done) msg.push("Плод с мутагеном: в курс опытной линии он не идёт.");
  if (LAB.ach) LAB.ach.ev("plant_eat", 1);
}
/* Время идёт (game.advanceTime): кончилось действие — сказать и отдать откат */
function minutes() {
  var g = LAB.game && LAB.game.G;
  if (!g || !g.plants || !g.plants.fx) return;
  var P = g.plants, now = nowOf(g), k, f, msg;
  for (k in P.fx) {
    f = P.fx[k];
    if (!f || f.until > now) continue;
    delete P.fx[k];
    msg = [];
    if (f.crash) {
      gm().bodyApply(f.crash, msg);
      if (f.crash.food < 0) msg = ["Мышцы требуют своё: сытость " + Math.round((g.body && g.body.food) || 0) + "."];
      else if (f.crash.wake < 0) msg = ["Откат: клонит в сон, бодрость " + Math.round((g.body && g.body.wake) || 0) + "."];
    }
    sayq("Действие плода прошло: " + STAT_N[k] + " снова " + heroStat(k) + "." + (msg.length ? " " + msg.join(" ") : ""));
  }
}
