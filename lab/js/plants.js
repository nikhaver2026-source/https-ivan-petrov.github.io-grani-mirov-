function pickPlants(o, t, rm, env) {
  var E = env.era, L = env.L, c = env.ctx, tl = String(t || "").toLowerCase(), cand = [], sum = 0, k, sp, w;
  if (env.sprout && c !== "okocrop") return SP.k_sprouts;
  for (k in SP) {
    sp = SP[k];
    if (!eraOk(sp, E) || !sp.kw || sp.sprout || SP2[k]) continue;
    if (sp.kw.test(tl) && (!sp.kwNeed || sp.kwNeed.test(tl)) && (!sp.kwCtx || sp.kwCtx[c] || (c === "okocrop" && sp.kwCtx.crop))) return sp;
  }
  var weigh = function (cc) {
    for (k in SP) {
      sp = SP[k];
      if (!eraOk(sp, E) || SP2[k] || sp.sprout) continue;
      w = (sp.ctx && sp.ctx[cc]) || 0;
      if (sp.fromL && L < sp.fromL) w = 0;
      if (sp.fromL && cc === "crop" && (L === 3 || L === 4) && sp.ctx && sp.ctx.lab) w = Math.max(w, 1.2); /* «Гидропоника» и «Генетические лаборатории»: опытные линии и в теплицах */
      if (w > 0) { cand.push([sp, w]); sum += w; }
    }
  };
  weigh(c);
  if (!cand.length && c === "okocrop") weigh("crop"); /* грядки ОКО там, где своих линий ОКО нет (Исток), — как сад */
  if (!cand.length) { /* нет своего вида на эту глубину и назначение — декоративный вид глубины */
    for (k in SP) { sp = SP[k]; if (eraOk(sp, E) && sp.spec === "decor" && !sp.kw && !SP2[k] && !sp.sprout && !sp.dead) { w = 1; cand.push([sp, w]); sum += w; } }
  }
  if (!cand.length) return null;
  var x = (h32(o.id + ":" + (CUR() ? CUR().key : "") + ":plant") % 100000) / 100000 * sum;
  for (var i = 0; i < cand.length; i++) { x -= cand[i][1]; if (x < 0) return cand[i][0]; }
  return cand[cand.length - 1][0];
}
