    kind: kind, rm: rm, live: live, mut: !!(rm && rm.fog) && live, rad: !!(rm && rm.rad), gas: !!(rm && rm.gas),
    /* у четверти аквариумов провод обогревателя у самой воды перемотан изолентой, а изолента отклеилась */
