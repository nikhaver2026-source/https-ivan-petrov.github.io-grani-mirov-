  { id: "sector", n: "Новый сектор", t: function () { return "Новый этаж. Лестница вниз обычно в другом конце. Навигатор — " + K("два пальца вправо", "N") + ": без карты этажа он ведёт постепенно, от точки к точке; режим навигатора выбирают в настройках."; } },
  { id: "seam", n: "Шов", t: function () { return "Это Шов. Здесь, под Ядром, механизмы глубин связаны между собой: что вы сделаете выше, отзовётся ниже. Документы найденного — в архиве, глава о глубинах — в руководстве."; } }
