#!/usr/bin/env node
/* Смысл обстановки глубоких блоков: каждая вещь в помещении должна быть к месту. Правила — по
   названию и описанию помещения: капсула восстановления — где спят и лечатся; автоматы с едой и
   напитками — не в стерильных боксах, холодильниках, вольерах и у топок; станция имплантов — где
   работают с телом и техникой; медстанция — где лечат; магнетрон и позитрон — где энергия; стенд
   задачи — не в спальне и не на кухне. Это подсказки к проверке глазами, не приговор.
   Запуск: node lab/tools/audit_deep.js [номер блока] */
"use strict";
const fs = require("fs"), path = require("path"), vm = require("vm");
const ROOT = path.resolve(__dirname, "..");
const only = process.argv[2] ? +process.argv[2] : 0;
const ctx = { console: { log() {}, warn() {}, error() {} }, Math, JSON, Object, Array, String, Number, Uint8Array, Int8Array, Int16Array, Int32Array, Error, Date, RegExp, Proxy };
ctx.globalThis = ctx; ctx.window = ctx; vm.createContext(ctx);
const load = f => { const p = path.join(ROOT, f); if (fs.existsSync(p)) vm.runInContext(fs.readFileSync(p, "utf8"), ctx, { filename: f }); };
["js/data.js", "js/texts.js", "js/lore.js", "js/b1.js", "js/b2.js", "js/b3.js", "js/b4.js", "js/b5.js", "js/deep.js", "js/world.js"].forEach(load);
const RULES = [
  { key: "capsule", ok: /спал|сон|сн[ау]|общежит|кают|палат|лазарет|медпункт|отдых|ночл|казарм|койк|кроват|изолятор|реанимац|приют|лежак|санатор|дрём|дрем|постел|барак|квартир|жиль|опочивал|покой|капсул/i, why: "капсула восстановления — там, где спят или лечатся" },
  { key: "coffee", bad: /стерил|холодильн|морозил|вольер|псарн|клетк|вивари|операционн|изолятор|реактор|топк|склад реактив|отстойник|грибниц|морг|автоклав|дезкамер|санпропуск/i, why: "кофейный автомат здесь не к месту", allow: /курилк|буфет|столов|чайн|кухн|отдых|кают-компан|бытовк|раздевал|кормокухн/i },
  { key: "drinks", bad: /стерил|холодильн|морозил|вольер|псарн|клетк|вивари|операционн|изолятор|реактор|топк|склад реактив|отстойник|грибниц|морг|автоклав|дезкамер|санпропуск/i, why: "автомат с напитками здесь не к месту", allow: /курилк|буфет|столов|чайн|кухн|отдых|кают-компан|бытовк|раздевал|кормокухн/i },
  { key: "vending", bad: /стерил|холодильн|морозил|вольер|псарн|операционн|изолятор|реактор|топк|отстойник|морг|дезкамер/i, why: "торговый автомат здесь не к месту" },
  { key: "implantlab", ok: /имплант|протез|кибер|мастерск|операцион|хирург|перчаточн|лаборат|медиц|лечеб|модиф|переделк|опытн|сборочн|ремонт|киберн|клиник|процедур/i, why: "станция имплантов — где работают с телом и техникой" },
  { key: "medst", ok: /мед|лазарет|палат|госпит|лечеб|аптек|процедур|операцион|санпропуск|душев|вивари|препаратор|перевяз|приёмн|приемн|реаним|изолятор|карантин|амбулатор|врач|фельдшер|сестр|бокс|полигон|арен|трасс|испыт|раздевал|душ/i, why: "медстанция — где лечат" },
  { key: "magnetron", ok: /энерг|реактор|генератор|подстанц|щитов|турбин|кот[её]л|машинн|электр|питан|трансформ|аккумулят|ядро|разлом|магнетрон/i, why: "магнетронная установка — где энергия" },
  { key: "positron", ok: /энерг|реактор|генератор|подстанц|турбин|кот[её]л|машинн|позитрон|ускорител|разлом|ядро|аномал|опытн/i, why: "позитронная установка — где энергия или опыты" },
  { key: "puzzle", bad: /спальн|кухн|столов|бан[яи]|прачечн|туалет|уборн|душев|морг|детск/i, why: "стенд с задачей здесь не к месту" },
  { key: "workbench", bad: /спальн|столов|палат|библиотек|архив|детск|бан[яи]|морг|туалет|исповед|молельн|часовн/i, why: "верстак здесь не к месту" }
];
let flags = 0;
for (let n = 6; n <= 15; n++) {
  if (only && n !== only) continue;
  const f = "js/d" + n + ".js";
  if (!fs.existsSync(path.join(ROOT, f))) continue;
  try { load(f); } catch (e) { console.log(`блок ${n}: не загружается (${e.message})`); continue; }
  const R = ctx.LAB.ROOMS, own = Object.keys(R).filter(k => k.indexOf("v" + n + "_") === 0);
  console.log(`\nБлок ${n}: помещений ${own.length}`);
  own.forEach(id => {
    const r = R[id], t = (r.n || "") + " " + (r.desc || "");
    Object.keys(r.obj || {}).forEach(k => RULES.filter(q => q.key === k).forEach(q => {
      if (q.allow && q.allow.test(r.n || "")) return;
      if ((q.ok && !q.ok.test(t)) || (q.bad && q.bad.test(t))) { flags++; console.log(`  ${id} «${r.n}»: ${k} — ${q.why}`); }
    }));
    if (r.trial && !/испыт|арен|полигон|камер|трасс|стенд|экзам|проб|тир|полос|бокс|зал|опыт/i.test(t)) { flags++; console.log(`  ${id} «${r.n}»: испытательная камера, но по описанию — не она`); }
    if (r.dark && /камер[аы] наблюд|под надзором/i.test(t)) { flags++; console.log(`  ${id} «${r.n}»: вне надзора, а в описании — надзор`); }
  });
}
console.log(`\nЗамечаний: ${flags}`);
