#!/bin/bash
# (4.1) Новый запуск игры в том же процессе после ухода в фон: страница должна ожить.
# Уход в фон усыпляет таймеры страницы (WebView.pauseTimers) — не одного окна, а процесса
# отрисовки страниц, общего для всех окон приложения. Прежде окно, закрытое после ухода в фон
# («Выход», смахнули из недавних, система закрыла окно), оставляло их усыплёнными, и новое окно
# в том же процессе получало спящую страницу: разметка разбирается («ready» в журнале есть), а
# всё, что идёт по таймерам, стоит — игра молчит, чтец экрана читает «Загрузка…». Так и писал
# игрок: «иногда игра не загружается».
# Здесь: обычный запуск (без самопроверки: с ней страница в фоне не засыпает) → «Домой»
# (страница уснула) → запуск новым окном (прежнее закрывается, процесс тот же) с самопроверкой.
# Её обход этажей начинается по таймеру страницы: строка «selftest tour» — таймеры идут.
#   bash lab/android/relaunch-check.sh          — ждём, что оживёт (новый APK)
#   bash lab/android/relaunch-check.sh stuck    — только сведения: встанет ли (прежний APK)
set -u
PKG=io.github.granimirov.lab
WANT=${1:-ok}
seen() { adb logcat -d -s LabJS:* 2>/dev/null | grep -E "$1" | tail -1 || true; }
wait_for() { local R="" i; for i in $(seq 1 "$2"); do R=$(seen "$1"); [ -n "$R" ] && break; sleep 2; done; echo "$R"; }
adb shell am force-stop $PKG
adb logcat -c
adb shell am start -W -n $PKG/.MainActivity > /dev/null
R1=$(wait_for "ready " 90)
P1=$(adb shell pidof $PKG | tr -d '\r' || true)
sleep 3
adb shell input keyevent KEYCODE_HOME
sleep 5
# новый APK отмечает в журнале, что страница в фоне уснула (прежний об этом не пишет)
SLEPT=$(seen "таймеры страницы усыплены")
adb logcat -c
# NEW_TASK | CLEAR_TASK: прежнее окно закрывается, новое открывается в том же процессе —
# как запуск после «Выхода», пока Android ещё держит процесс игры
adb shell am start -W -f 0x10008000 -n $PKG/.MainActivity --ez lab_selftest true > /dev/null
R2=$(wait_for "ready " 60)
ST=""; TOUR=""
[ -n "$R2" ] && ST=$(wait_for "selftest start" 30)
[ -n "$ST" ] && TOUR=$(wait_for "selftest tour" 45)
WOKE=$(seen "таймеры страницы разбужены")
P2=$(adb shell pidof $PKG | tr -d '\r' || true)
SAME=""; [ -n "$P1" ] && [ "$P1" = "$P2" ] && SAME=" (тот же)"
if [ -z "$R2" ]; then NEWW="страница не разобралась — стоит на «Загрузке»"
elif [ -z "$ST" ]; then NEWW="страница разобрана, но самопроверка не началась — стоит на «Загрузке»"
elif [ -z "$TOUR" ]; then NEWW="страница разобрана, но таймеры стоят — игра молчит, стоит на «Загрузке»"
else NEWW="страница ожила, таймеры идут"; fi
echo "первый запуск: $([ -n "$R1" ] && echo 'страница загрузилась' || echo 'страница НЕ загрузилась'), процесс ${P1:-нет}"
echo "уход в фон: $([ -n "$SLEPT" ] && echo 'таймеры страницы усыплены' || echo 'отметки об усыплении таймеров нет')"
[ -n "$WOKE" ] && echo "прежнее окно при закрытии: таймеры страницы разбужены"
echo "новое окно после фона: $NEWW, процесс ${P2:-нет}$SAME"
adb shell am force-stop $PKG
[ "$WANT" = "stuck" ] && exit 0
[ -n "$SLEPT" ] || { echo "страница в фоне не уснула — сценарий ничего не проверил"; exit 1; }
[ -n "$R1" ] && [ -n "$TOUR" ] || { echo "новое окно после фона не ожило"; exit 1; }
echo "запуск после фона в том же процессе: страница оживает"
